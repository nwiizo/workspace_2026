// 003 - Longest Circular Road (★4)
// https://atcoder.jp/contests/typical90/tasks/typical90_c
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたは村の道路計画者です。
// N 個の村が木のように道でつながっています。
//
// 「木のように」とは、どういう意味でしょう？
// - どの村からどの村へも、必ず1通りの道順で行ける
// - 行き止まりや、ぐるっと回れるループがない
//
//   村1 --- 村2 --- 村3
//            |
//           村4
//
// 今、新しい道路を1本だけ追加して、
// 「サイクル（ループ）」を作りたいと思っています。
//
// サイクルができると、村祭りで「ぐるっと一周パレード」ができます！
// パレードのルートは長い方が盛り上がるので、
// できるだけ長いサイクルを作りたいのです。
//
// 【質問】
// 道路を1本追加したとき、作れる最長のサイクルは何本の道を通る？
//
// ============================================================================
// 【解法：木の直径 + 1】
// ============================================================================
//
// 実は、答えは「木の直径 + 1」になります！
//
// 【木の直径とは？】
// 木の中で「最も遠い2点間の距離」のこと。
//
//   村1 --- 村2 --- 村3 --- 村4
//            |
//           村5
//
// この木の直径は「村1 → 村2 → 村3 → 村4」の 3 です。
// （村5からは村1か村4までが最遠で距離2）
//
// 【なぜ直径+1がサイクルになる？】
//
// 直径の両端（村1と村4）を新しい道路で結ぶと：
//
//   村1 --- 村2 --- 村3 --- 村4
//    |                       |
//    +-------新しい道路-------+
//
// サイクルの長さ = 直径（3本の道）+ 新しい道路（1本）= 4
//
// 他の場所に道を追加しても、これより長いサイクルは作れません。
// なぜなら、直径が「最も遠い2点」だから！
//
// ============================================================================
// 【木の直径の求め方 - 2回のBFS】
// ============================================================================
//
// 【BFS（幅優先探索）とは？】
//
// 「波紋」のように、近い場所から順番に探索する方法です。
//
// 例: 村2から探索開始
// 1. 村2を訪問（距離0）
// 2. 村2の隣人（村1,3,5）を訪問（距離1）
// 3. さらにその隣人（村4）を訪問（距離2）
//
// 【直径を求めるアルゴリズム】
//
// 1. どこか適当な点（村0）からBFSして、最遠点 u を見つける
// 2. u からBFSして、最遠点 v を見つける
// 3. u-v 間の距離が直径！
//
// なぜこれで正しいの？
// → 最初のBFSで「端っこの1つ」が必ず見つかる。
//   そこからBFSすると「もう片方の端っこ」が見つかる。
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - BFS: O(N) （各頂点を1回ずつ訪問）
// - 2回やるので O(2N) = O(N)
//
// N = 100,000 でも余裕で間に合います。
//
// ============================================================================

use proconio::input;
use proconio::marker::Usize1;
use std::collections::VecDeque;

fn main() {
    input! {
        n: usize,   // 村の数
        // 道路の情報を読み込む
        // Usize1 は「1-indexed を 0-indexed に変換」してくれる便利機能
        // 入力が 1, 2, 3... で来ても、内部では 0, 1, 2... として扱える
        edges: [(Usize1, Usize1); n - 1],
    }
    println!("{}", solve(n, &edges));
}

/// 隣接リストを構築する
///
/// 【隣接リストとは？】
///
/// グラフを表現する方法の一つ。
/// 各頂点について「どの頂点と繋がっているか」をリストで持つ。
///
/// 例: 0-1-2 の直線グラフ
/// graph[0] = [1]     （頂点0は頂点1と繋がっている）
/// graph[1] = [0, 2]  （頂点1は頂点0と2と繋がっている）
/// graph[2] = [1]     （頂点2は頂点1と繋がっている）
fn build_graph(n: usize, edges: &[(usize, usize)]) -> Vec<Vec<usize>> {
    // vec![vec![]; n] は「空のベクタを n 個持つベクタ」を作る
    let mut graph = vec![vec![]; n];

    for &(a, b) in edges {
        // 無向グラフなので、両方向に辺を追加
        graph[a].push(b); // a → b
        graph[b].push(a); // b → a
    }

    graph
}

/// BFSで最遠点とその距離を返す
///
/// # 戻り値
/// (最遠点のインデックス, 最遠点までの距離)
fn bfs_farthest(graph: &[Vec<usize>], start: usize) -> (usize, usize) {
    let n = graph.len();

    // -------------------------------------------------------------------------
    // 【距離配列の初期化】
    //
    // dist[v] = start から v までの距離
    // 最初は「まだ訪問していない」という意味で usize::MAX を入れておく
    // -------------------------------------------------------------------------
    let mut dist = vec![usize::MAX; n];

    // -------------------------------------------------------------------------
    // 【キュー（待ち行列）】
    //
    // VecDeque は「両端キュー」。
    // push_back で後ろに追加、pop_front で前から取り出す。
    //
    // BFS では「先に見つけたものを先に処理する」（FIFO: First In, First Out）
    // これにより、距離の近い順に処理できる。
    // -------------------------------------------------------------------------
    let mut queue = VecDeque::from([start]);
    dist[start] = 0; // スタート地点は距離0

    // -------------------------------------------------------------------------
    // 【BFSのメインループ】
    //
    // キューが空になるまで繰り返す。
    // while let Some(v) = queue.pop_front() は、
    // 「キューから1つ取り出して、それを v とする。空ならループ終了」
    // という意味の Rust らしい書き方。
    // -------------------------------------------------------------------------
    while let Some(v) = queue.pop_front() {
        // v の隣人をすべて見る
        for &next in &graph[v] {
            // まだ訪問していない隣人だけ処理
            if dist[next] == usize::MAX {
                dist[next] = dist[v] + 1; // 距離を記録
                queue.push_back(next); // キューに追加（後で処理）
            }
        }
    }

    // -------------------------------------------------------------------------
    // 【最遠点を探す】
    //
    // 距離配列の中で、距離が最大の頂点を見つける。
    //
    // .into_iter(): 所有権を移動してイテレータに
    // .enumerate(): (インデックス, 値) のペアにする
    // .filter(): 条件に合うものだけ残す
    // .max_by_key(): 特定の値で最大のものを選ぶ
    // -------------------------------------------------------------------------
    dist.into_iter()
        .enumerate()
        .filter(|&(_, d)| d != usize::MAX) // 未訪問は除外
        .max_by_key(|&(_, d)| d) // 距離が最大のものを選ぶ
        .unwrap_or((start, 0)) // 見つからなければスタート地点（安全策）
}

fn solve(n: usize, edges: &[(usize, usize)]) -> usize {
    let graph = build_graph(n, edges);

    // -------------------------------------------------------------------------
    // 【2回BFSで木の直径を求める】
    //
    // 1回目: 適当な点（0番）から最遠点 u を見つける
    // 2回目: u から最遠点を見つけ、その距離が直径
    // -------------------------------------------------------------------------
    let (u, _) = bfs_farthest(&graph, 0); // 1回目のBFS
    let (_, diameter) = bfs_farthest(&graph, u); // 2回目のBFS

    // 直径 + 1 = サイクルの長さ（道の数 = 通る村の数）
    diameter + 1
}

