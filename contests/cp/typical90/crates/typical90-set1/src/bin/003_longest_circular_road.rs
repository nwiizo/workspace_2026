#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn path_graph() {
        // 直線グラフ: 0-1-2-3
        //
        //   0 --- 1 --- 2 --- 3
        //
        // 直径 = 3（0から3まで）
        // 0と3を結ぶとサイクル長 = 4
        let edges = vec![(0, 1), (1, 2), (2, 3)];
        assert_eq!(solve(4, &edges), 4);
    }

    #[test]
    fn star_graph() {
        // 星型グラフ: 0を中心に1,2,3が繋がる
        //
        //       1
        //       |
        //   2 - 0 - 3
        //
        // 直径 = 2（例: 1から2まで）
        // 1と2を結ぶとサイクル長 = 3
        let edges = vec![(0, 1), (0, 2), (0, 3)];
        assert_eq!(solve(4, &edges), 3);
    }

    #[test]
    fn single_edge() {
        // 最小のケース: 2頂点
        //
        //   0 --- 1
        //
        // 直径 = 1
        // 0と1の間にもう1本道を作るとサイクル長 = 2
        let edges = vec![(0, 1)];
        assert_eq!(solve(2, &edges), 2);
    }

    #[test]
    fn y_shape() {
        // Y字型グラフ
        //
        //   0
        //   |
        //   1 --- 3
        //   |
        //   2
        //
        // 直径 = 2（0から2、0から3、2から3のいずれか）
        // サイクル長 = 3
        let edges = vec![(0, 1), (1, 2), (1, 3)];
        assert_eq!(solve(4, &edges), 3);
    }
}
