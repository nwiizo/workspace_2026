// 017 - Crossing Segments (★7)
// https://atcoder.jp/contests/typical90/tasks/typical90_q
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// 円形のテーブルに N 人が座っています。
// M 組のペアがそれぞれ紐で繋がっています（弦）。
//
// 紐が交差しているペアの数を数えてください。
//
//       0
//    5     1
//
//    4     2
//       3
//
// 例: 弦(0,3), (1,4), (2,5) がある場合:
//
//   0---3 と 1---4: 交差する（0 < 1 < 3 < 4）
//   0---3 と 2---5: 交差する（0 < 2 < 3 < 5）
//   1---4 と 2---5: 交差する（1 < 2 < 4 < 5）
//
// 答え: 3組
//
// ============================================================================
// 【交差の条件】
// ============================================================================
//
// 弦 (L1, R1) と弦 (L2, R2) が交差する条件（L < R と正規化済み）:
//
// L1 < L2 < R1 < R2
//
// つまり、一方の弦の内側にもう一方の始点があり、終点は外側にある状態。
//
// 【交差しないケース】
// - 完全に分離: L1 < R1 < L2 < R2
// - 一方が他方を含む: L1 < L2 < R2 < R1
//
// ============================================================================
// 【解法：ソート + BIT（Binary Indexed Tree）】
// ============================================================================
//
// 【アイデア】
//
// 弦を L の小さい順にソートして処理する。
//
// 弦 (L, R) を処理するとき:
// - 既に処理した弦の中で、R' が (L, R) の間にあるものと交差する
// - つまり L < R' < R を満たす R' の数が交差数
//
// 【BIT（フェニック木）の役割】
//
// BIT で「各 R の位置に何本の弦があるか」を管理する。
// 区間 [L+1, R-1] にある R の総数を O(log N) で取得できる。
//
// ============================================================================
// 【BIT（Binary Indexed Tree）とは？】
// ============================================================================
//
// 「累積和」を効率的に管理するデータ構造。
//
// - 点更新: O(log N)
// - 区間和クエリ: O(log N)
//
// セグメント木より実装が簡単で、定数倍も軽い。
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - ソート: O(M log M)
// - 各弦の処理: O(log N)
// - 合計: O(M log M + M log N) = O(M log N)
//
// ============================================================================

use proconio::input;
use proconio::marker::Usize1;

fn main() {
    input! {
        n: usize,
        m: usize,
        segments: [(Usize1, Usize1); m],
    }
    println!("{}", solve(n, &segments));
}

fn solve(n: usize, segments: &[(usize, usize)]) -> i64 {
    // -------------------------------------------------------------------------
    // 【前処理: L < R に正規化してソート】
    //
    // 円周上なので、小さい方を L、大きい方を R とする
    // -------------------------------------------------------------------------
    let mut segs: Vec<(usize, usize)> = segments
        .iter()
        .map(|&(l, r)| if l < r { (l, r) } else { (r, l) })
        .collect();
    segs.sort_by_key(|&(l, _)| l);

    // -------------------------------------------------------------------------
    // 【BIT で R の位置を管理】
    // -------------------------------------------------------------------------
    let mut bit = Bit::new(n);
    let mut ans = 0i64;

    for (l, r) in segs {
        // ---------------------------------------------------------------------
        // 【交差数をカウント】
        //
        // L1 < L < R1 < R となる弦 (L1, R1) と交差する
        // → R1 が (L, R) の開区間にある弦の数
        // ---------------------------------------------------------------------
        if l + 1 < r {
            ans += bit.sum(l + 1, r - 1);
        }

        // ---------------------------------------------------------------------
        // 【この弦の R を BIT に追加】
        // ---------------------------------------------------------------------
        bit.add(r, 1);
    }

    ans
}

// =============================================================================
// 【BIT（Binary Indexed Tree / フェニック木）】
// =============================================================================
#[allow(clippy::upper_case_acronyms)]
struct Bit {
    data: Vec<i64>,
}

impl Bit {
    /// n 要素の BIT を作成
    fn new(n: usize) -> Self {
        Self {
            data: vec![0; n + 1],
        }
    }

    /// 位置 i に x を加算
    fn add(&mut self, mut i: usize, x: i64) {
        i += 1; // 1-indexed に変換
        while i < self.data.len() {
            self.data[i] += x;
            i += i & i.wrapping_neg(); // 最下位ビットを加算
        }
    }

    /// [0, i) の累積和
    fn prefix_sum(&self, mut i: usize) -> i64 {
        let mut s = 0;
        while i > 0 {
            s += self.data[i];
            i -= i & i.wrapping_neg(); // 最下位ビットを減算
        }
        s
    }

    /// [l, r] の区間和
    fn sum(&self, l: usize, r: usize) -> i64 {
        if l > r {
            return 0;
        }
        self.prefix_sum(r + 1) - self.prefix_sum(l)
    }
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_bit() {
        let mut bit = Bit::new(10);
        bit.add(2, 1);
        bit.add(5, 1);
        bit.add(7, 1);

        assert_eq!(bit.sum(0, 9), 3);  // 全体
        assert_eq!(bit.sum(3, 6), 1);  // 5だけ
        assert_eq!(bit.sum(2, 5), 2);  // 2と5
    }

    #[test]
    fn example_crossing() {
        // 円周上に0,1,2,3,4,5の6点
        // 弦: (0,3), (1,4), (2,5)
        //
        // 交差条件: L1 < L2 < R1 < R2
        //
        // (0,3)と(1,4): 0<1<3<4 ✓
        // (0,3)と(2,5): 0<2<3<5 ✓
        // (1,4)と(2,5): 1<2<4<5 ✓
        //
        // 答え: 3
        assert_eq!(solve(6, &[(0, 3), (1, 4), (2, 5)]), 3);
    }

    #[test]
    fn no_crossing() {
        // (0,1), (2,3) は交差しない
        // 0 < 1 < 2 < 3 で完全に分離
        assert_eq!(solve(4, &[(0, 1), (2, 3)]), 0);
    }

    #[test]
    fn nested_no_crossing() {
        // (0,3), (1,2) は交差しない
        // 0 < 1 < 2 < 3 で (1,2) が (0,3) に含まれている
        assert_eq!(solve(4, &[(0, 3), (1, 2)]), 0);
    }

    #[test]
    fn single_segment() {
        // 1本の弦だけなら交差なし
        assert_eq!(solve(4, &[(0, 2)]), 0);
    }
}
