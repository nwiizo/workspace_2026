// 020 - Log Inequality (★3)
// https://atcoder.jp/contests/typical90/tasks/typical90_t
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// 数学の問題です。
//
// 3つの正の整数 a, b, c が与えられます。
// 次の不等式が成り立つか判定してください。
//
//   log₂(a) < b × log₂(c)
//
// つまり「a の2を底とする対数」が「c の2を底とする対数の b 倍」より小さいか？
//
// ============================================================================
// 【解法：対数を使わずに整数で比較】
// ============================================================================
//
// 【なぜ対数を使わない？】
//
// 浮動小数点演算は誤差が生じる。
// 特に境界ケース（ほぼ等しい場合）で正しく判定できないことがある。
//
// 【対数の性質を使った変換】
//
// log₂(a) < b × log₂(c)
// ⟺ log₂(a) < log₂(c^b)  （対数の性質: b × log₂(c) = log₂(c^b)）
// ⟺ a < c^b              （対数関数は単調増加）
//
// これで整数の比較に帰着できる！
//
// 【オーバーフロー対策】
//
// c^b は非常に大きくなる可能性がある（最大 10^18 × 10^18 以上）。
// 計算途中でオーバーフローする場合、「c^b > a は確実」と判定できる。
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - c^b の計算: O(b)
// - ただし途中で a を超えたら打ち切れるので、実際はもっと速い
//
// ============================================================================

use proconio::input;

fn main() {
    input! {
        a: u64,     // 比較対象の数
        b: u32,     // 指数
        c: u64,     // 底
    }

    if check(a, b, c) {
        println!("Yes");
    } else {
        println!("No");
    }
}

/// a < c^b を判定（オーバーフロー対策付き）
///
/// 条件を満たすなら true、そうでなければ false を返す。
fn check(a: u64, b: u32, c: u64) -> bool {
    // -------------------------------------------------------------------------
    // 【c^b を順次計算】
    //
    // オーバーフローまたは a を超えた時点で true を返す
    // -------------------------------------------------------------------------
    let mut result: u64 = 1;

    for _ in 0..b {
        // オーバーフローチェック: result × c > u64::MAX になるか
        if result > u64::MAX / c {
            return true; // c^b は非常に大きい → a より確実に大きい
        }

        result *= c;

        // 途中で a を超えたら早期終了
        if result > a {
            return true;
        }
    }

    // 最終的に a < result か判定
    a < result
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn example1() {
        // log₂(2) = 1
        // 2 × log₂(2) = 2
        // 1 < 2 → Yes
        assert!(check(2, 2, 2));
    }

    #[test]
    fn example2() {
        // log₂(4) = 2
        // 1 × log₂(4) = 2
        // 2 < 2 は偽 → No
        assert!(!check(4, 1, 4));
    }

    #[test]
    fn large_power() {
        // a = 10^18
        // b = 100, c = 2
        // 2^100 は約 10^30 → 10^18 より圧倒的に大きい → Yes
        assert!(check(1_000_000_000_000_000_000, 100, 2));
    }

    #[test]
    fn c_is_one() {
        // c = 1 → c^b = 1
        // a = 2 > 1 → No
        assert!(!check(2, 100, 1));
    }

    #[test]
    fn equal_case() {
        // a = 8, b = 3, c = 2
        // 2^3 = 8
        // 8 < 8 は偽 → No
        assert!(!check(8, 3, 2));
    }

    #[test]
    fn just_smaller() {
        // a = 7, b = 3, c = 2
        // 2^3 = 8
        // 7 < 8 → Yes
        assert!(check(7, 3, 2));
    }

    #[test]
    fn b_is_zero() {
        // b = 0 → c^0 = 1
        // a = 2 > 1 → No
        // a = 0 < 1 → Yes
        assert!(!check(2, 0, 5));
        assert!(!check(1, 0, 5)); // 1 < 1 は偽
    }

    #[test]
    fn overflow_scenario() {
        // c^b が u64 をオーバーフローするケース
        // c = 10^9, b = 10 → 10^90 >> u64::MAX
        // a がどんな値でも true
        assert!(check(1, 10, 1_000_000_000));
    }
}
