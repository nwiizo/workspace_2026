// 011 - Gravy Jobs (★6)
// https://atcoder.jp/contests/typical90/tasks/typical90_k
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたはフリーランスの開発者です。
// N 個の仕事依頼が来ていて、それぞれ:
// - 締切 D_i: この日までに完了しないと報酬がもらえない
// - 所要時間 C_i: 仕事にかかる日数
// - 報酬 S_i: 成功したらもらえるお金
//
// 時刻 0 からスタートして、1つずつ順番に仕事をこなします。
// 仕事を終えた時刻が締切以内なら報酬をゲット！
//
// 得られる報酬の最大値を求めてください。
//
// 例:
//   仕事A: 締切4日, 所要2日, 報酬10万
//   仕事B: 締切4日, 所要3日, 報酬15万
//   仕事C: 締切2日, 所要1日, 報酬5万
//
// 戦略1: A → B
//   A: 時刻0-2で完了 (締切4 OK) → 報酬10万
//   B: 時刻2-5で完了 (締切4 NG) → 報酬なし
//   合計: 10万
//
// 戦略2: C → B
//   C: 時刻0-1で完了 (締切2 OK) → 報酬5万
//   B: 時刻1-4で完了 (締切4 OK) → 報酬15万
//   合計: 20万 ← 最適！
//
// ============================================================================
// 【解法：締切順ソート + ナップサックDP】
// ============================================================================
//
// 【なぜ締切順にソート？】
//
// 締切が早い仕事は、早めにやらないと間に合わなくなる。
// 締切順に処理すると、「この仕事をやる/やらない」の選択が単純になる。
//
// 【ナップサックDP】
//
// dp[t] = 時刻 t までに得られる報酬の最大値
//
// 締切順に各仕事を見て:
// - 「この仕事をやる」場合: 締切以内に終われるか確認
// - 「この仕事をやらない」場合: dp[t] はそのまま
//
// 【遷移】
//
// 仕事 (締切D, 所要C, 報酬S) を処理するとき:
//
// 時刻 t-C に終わっていれば、この仕事を追加できる。
// → dp[t] = max(dp[t], dp[t-C] + S)
//
// ただし t <= D（締切以内に終わる必要がある）
//
// 【後ろから更新する理由】
//
// 前から更新すると、同じ仕事を何度も使ってしまう！
// → 0-1ナップサック問題と同じ理由
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - ソート: O(N log N)
// - DP更新: O(N × max_D)
// - 合計: O(N × max_D)
//
// max_D が大きい場合は座標圧縮などが必要になることもあるが、
// この問題では max_D <= 10^5 なので大丈夫。
//
// ============================================================================

use proconio::input;

fn main() {
    input! {
        n: usize,
        jobs: [(usize, usize, i64); n], // (D, C, S) = (締切, 所要時間, 報酬)
    }
    println!("{}", solve(&jobs));
}

fn solve(jobs: &[(usize, usize, i64)]) -> i64 {
    // -------------------------------------------------------------------------
    // 【締切でソート】
    //
    // 締切が早い順に処理することで、DP の更新がシンプルになる
    // -------------------------------------------------------------------------
    let mut jobs = jobs.to_vec();
    jobs.sort_by_key(|&(d, _, _)| d);

    // -------------------------------------------------------------------------
    // 【最大締切を求める】
    //
    // DP配列のサイズを決めるため
    // -------------------------------------------------------------------------
    let max_d = jobs.iter().map(|&(d, _, _)| d).max().unwrap_or(0);

    // -------------------------------------------------------------------------
    // 【DP配列の初期化】
    //
    // dp[t] = 時刻 t までに得られる報酬の最大値
    // 最初は何もしていないので全て 0
    // -------------------------------------------------------------------------
    let mut dp = vec![0i64; max_d + 1];

    // -------------------------------------------------------------------------
    // 【各仕事を処理】
    // -------------------------------------------------------------------------
    for (deadline, cost, score) in jobs {
        // 後ろから更新（同じ仕事を複数回使わないため）
        // t: 仕事が終わる時刻（cost から deadline まで）
        for t in (cost..=deadline).rev() {
            // t-cost 時点で終わっていれば、この仕事を追加できる
            // 仕事を追加した場合の報酬と、しない場合の報酬を比較
            dp[t] = dp[t].max(dp[t - cost] + score);
        }
    }

    // -------------------------------------------------------------------------
    // 【答え】
    //
    // どの時刻で終わっても良いので、最大値を取る
    // -------------------------------------------------------------------------
    *dp.iter().max().unwrap_or(&0)
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn example1() {
        // 仕事A: 締切4, 所要2, 報酬10
        // 仕事B: 締切4, 所要3, 報酬15
        // 仕事C: 締切2, 所要1, 報酬5
        //
        // 最適: C(0-1) + B(1-4) = 5 + 15 = 20
        let jobs = vec![(4, 2, 10), (4, 3, 15), (2, 1, 5)];
        assert_eq!(solve(&jobs), 20);
    }

    #[test]
    fn single_job() {
        // 1つの仕事だけ
        let jobs = vec![(5, 3, 100)];
        assert_eq!(solve(&jobs), 100);
    }

    #[test]
    fn impossible_job() {
        // 締切より所要時間が長い → 絶対に間に合わない
        let jobs = vec![(2, 5, 100)];
        assert_eq!(solve(&jobs), 0);
    }

    #[test]
    fn overlapping_jobs() {
        // 両方はできないケース
        // 仕事A: 締切3, 所要3, 報酬100
        // 仕事B: 締切3, 所要3, 報酬50
        // → Aだけやる方が得
        let jobs = vec![(3, 3, 100), (3, 3, 50)];
        assert_eq!(solve(&jobs), 100);
    }

    #[test]
    fn multiple_jobs() {
        // 複数の仕事を組み合わせる
        // 仕事A: 締切5, 所要2, 報酬50
        // 仕事B: 締切5, 所要2, 報酬60
        // 仕事C: 締切5, 所要2, 報酬40
        // → A + B = 110 が最適
        let jobs = vec![(5, 2, 50), (5, 2, 60), (5, 2, 40)];
        assert_eq!(solve(&jobs), 110);
    }
}
