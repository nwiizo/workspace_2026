// 016 - Minimum Coins (★3)
// https://atcoder.jp/contests/typical90/tasks/typical90_p
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたはコンビニのレジ係です。
// 3種類の硬貨（A円、B円、C円）を使って、ちょうど N 円を支払います。
//
// 使う硬貨の枚数を最小にしてください。
//
// 例: N=15円、硬貨=1円・5円・10円
//
// 支払い方:
// - 1円×15 = 15枚
// - 1円×5 + 10円×1 = 6枚
// - 5円×1 + 10円×1 = 2枚 ← 最小！
//
// ============================================================================
// 【解法：全探索】
// ============================================================================
//
// 【なぜ全探索で間に合う？】
//
// 制約: 各硬貨は最大 9999 枚まで使える
// → A円硬貨の枚数 i と B円硬貨の枚数 j を全探索
// → C円硬貨の枚数は (N - A×i - B×j) / C で計算
//
// 計算量: O(9999²) ≈ 10^8
// これはギリギリ間に合う（実際はもっと速い枝刈りあり）
//
// 【枝刈り】
// - A×i > N なら i はこれ以上増やさなくていい → break
// - A×i + B×j > N なら j はこれ以上増やさなくていい → break
//
// これにより実際の計算量は O((N/A) × (N/B)) くらいに抑えられる
//
// ============================================================================
// 【貪欲法が使えない理由】
// ============================================================================
//
// 「大きい硬貨から使う」貪欲法は、この問題では最適解を出さないことがある。
//
// 例: N=6円、硬貨=1円・3円・4円
//
// 貪欲法: 4円×1 + 1円×2 = 3枚
// 最適解: 3円×2 = 2枚
//
// このように、硬貨の組み合わせによっては貪欲法が失敗する。
// → 全探索が必要
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - 最悪: O(max_coins²) = O(10^8)
// - 実際: 枝刈りによりもっと速い
//
// ============================================================================

use proconio::input;

fn main() {
    input! {
        n: i64,     // 支払う金額
        a: i64,     // 硬貨1の額面
        b: i64,     // 硬貨2の額面
        c: i64,     // 硬貨3の額面
    }
    println!("{}", solve(n, a, b, c));
}

fn solve(n: i64, a: i64, b: i64, c: i64) -> i64 {
    // -------------------------------------------------------------------------
    // 【制約】
    //
    // 問題文より、各硬貨は最大 9999 枚まで使える
    // -------------------------------------------------------------------------
    let max_coins = 9999;
    let mut ans = i64::MAX;

    // -------------------------------------------------------------------------
    // 【全探索】
    //
    // i: A円硬貨の枚数
    // j: B円硬貨の枚数
    // k: C円硬貨の枚数（計算で求める）
    // -------------------------------------------------------------------------
    for i in 0..=max_coins {
        // 枝刈り: A円硬貨だけで N 円を超えたら終了
        if a * i > n {
            break;
        }

        for j in 0..=max_coins {
            let used = a * i + b * j;

            // 枝刈り: A円 + B円 で N 円を超えたら終了
            if used > n {
                break;
            }

            // 残りを C円硬貨で払えるか？
            let remaining = n - used;
            if remaining % c == 0 {
                let k = remaining / c;

                // k も制約内か確認
                if k <= max_coins {
                    ans = ans.min(i + j + k);
                }
            }
        }
    }

    ans
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn example1() {
        // 15円を1円・5円・10円で支払う
        // 最適: 5円×1 + 10円×1 = 2枚
        assert_eq!(solve(15, 1, 5, 10), 2);
    }

    #[test]
    fn example2() {
        // 20円を1円・5円・10円で支払う
        // 最適: 10円×2 = 2枚
        assert_eq!(solve(20, 1, 5, 10), 2);
    }

    #[test]
    fn all_same() {
        // 30円を10円×3で支払う
        assert_eq!(solve(30, 10, 10, 10), 3);
    }

    #[test]
    fn greedy_fails() {
        // 貪欲法が失敗するケース
        // 6円を1円・3円・4円で支払う
        // 貪欲: 4円×1 + 1円×2 = 3枚
        // 最適: 3円×2 = 2枚
        assert_eq!(solve(6, 1, 3, 4), 2);
    }

    #[test]
    fn only_one_coin() {
        // 100円を1円だけで支払う
        assert_eq!(solve(100, 1, 100, 100), 1);
    }

    #[test]
    fn large_amount() {
        // 大きな金額
        // 9999円を1円・2円・3円で支払う
        // 最適: 3円×3333 = 3333枚
        assert_eq!(solve(9999, 1, 2, 3), 3333);
    }
}
