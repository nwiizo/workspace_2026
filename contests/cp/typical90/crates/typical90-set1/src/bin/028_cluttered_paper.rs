// 028 - Cluttered Paper (★4)
// https://atcoder.jp/contests/typical90/tasks/typical90_ab
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// 机の上に紙が何枚も重なっています。
//
// N 枚の長方形の紙が置かれます。
// 各紙は座標 (x1, y1) から (x2, y2) の範囲を覆います。
//
// 「1枚以上の紙で覆われている面積」の合計を求めてください。
// （重なっている部分は1回だけカウント）
//
// 例:
//   紙1: (0,0)-(2,2) → 面積4
//   紙2: (1,1)-(3,3) → 面積4
//
//   +---+
//   | +-+-+
//   +-+-+ |
//     +---+
//
// 重なり部分 (1,1)-(2,2) は面積1
// 答え: 4 + 4 - 1 = 7
//
// ============================================================================
// 【解法：2次元いもす法 + 座標圧縮】
// ============================================================================
//
// 【いもす法とは？】
//
// 区間への加算を効率的に行う手法。
//
// 1次元の例: 区間 [2, 5) に +1 する
// - diff[2] += 1
// - diff[5] -= 1
// - 累積和を取ると [0,0,1,1,1,0,0,...] になる
//
// 2次元でも同様に、長方形の4隅で ±1 する。
//
// 【座標圧縮】
//
// 座標が最大 10^9 だと、そのまま配列にできない。
// → 使う座標だけを列挙し、インデックスに変換
//
// 例: x座標が {0, 2, 3, 100} なら {0, 1, 2, 3} に圧縮
//
// 【アルゴリズム】
//
// 1. 全ての x, y 座標を収集・ソート・重複除去
// 2. 座標 → インデックスの変換関数を作る
// 3. 各長方形について、いもす法で ±1 を記録
// 4. 累積和を取って、各セルの「何枚の紙が重なっているか」を計算
// 5. 1枚以上重なっているセルの面積を合計
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - 座標の数: O(N)
// - 2次元配列のサイズ: O(N²) 最悪
// - 累積和: O(N²)
// - 合計: O(N² log N)
//
// ============================================================================

use proconio::input;

fn main() {
    input! {
        n: usize,
        rects: [(i32, i32, i32, i32); n], // (x1, y1, x2, y2)
    }
    println!("{}", solve(&rects));
}

#[allow(clippy::needless_range_loop)]
fn solve(rects: &[(i32, i32, i32, i32)]) -> i64 {
    // -------------------------------------------------------------------------
    // 【座標圧縮】
    //
    // 全ての x, y 座標を収集してソート・重複除去
    // -------------------------------------------------------------------------
    let mut xs: Vec<i32> = rects.iter().flat_map(|&(x1, _, x2, _)| [x1, x2]).collect();
    let mut ys: Vec<i32> = rects.iter().flat_map(|&(_, y1, _, y2)| [y1, y2]).collect();
    xs.sort_unstable();
    xs.dedup();
    ys.sort_unstable();
    ys.dedup();

    // 座標 → インデックスへの変換
    let x_to_idx = |x: i32| xs.binary_search(&x).unwrap();
    let y_to_idx = |y: i32| ys.binary_search(&y).unwrap();

    let w = xs.len();
    let h = ys.len();

    // -------------------------------------------------------------------------
    // 【2次元いもす法用の差分配列】
    //
    // diff[i][j] = セル (i, j) に対する変化量
    // -------------------------------------------------------------------------
    let mut diff = vec![vec![0i32; h + 1]; w + 1];

    for &(x1, y1, x2, y2) in rects {
        let (ix1, ix2) = (x_to_idx(x1), x_to_idx(x2));
        let (iy1, iy2) = (y_to_idx(y1), y_to_idx(y2));

        // ---------------------------------------------------------------------
        // 【いもす法: 4隅で ±1】
        //
        //   (ix1, iy1) +1    (ix2, iy1) -1
        //       +---------------+
        //       |               |
        //       |   長方形     |
        //       |               |
        //       +---------------+
        //   (ix1, iy2) -1    (ix2, iy2) +1
        // ---------------------------------------------------------------------
        diff[ix1][iy1] += 1;
        diff[ix1][iy2] -= 1;
        diff[ix2][iy1] -= 1;
        diff[ix2][iy2] += 1;
    }

    // -------------------------------------------------------------------------
    // 【累積和を取る】
    //
    // まず x 方向、次に y 方向に累積和
    // -------------------------------------------------------------------------
    for i in 0..w {
        for j in 0..h {
            if i > 0 {
                diff[i][j] += diff[i - 1][j];
            }
        }
    }
    for i in 0..w {
        for j in 0..h {
            if j > 0 {
                diff[i][j] += diff[i][j - 1];
            }
        }
    }

    // -------------------------------------------------------------------------
    // 【面積の計算】
    //
    // diff[i][j] > 0 なら、セル (i, j) は1枚以上の紙で覆われている
    // セルの実際のサイズは (xs[i+1] - xs[i]) × (ys[j+1] - ys[j])
    // -------------------------------------------------------------------------
    let mut total = 0i64;
    for i in 0..w - 1 {
        for j in 0..h - 1 {
            if diff[i][j] > 0 {
                let width = (xs[i + 1] - xs[i]) as i64;
                let height = (ys[j + 1] - ys[j]) as i64;
                total += width * height;
            }
        }
    }

    total
}

