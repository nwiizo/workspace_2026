#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn single_rect() {
        // 1枚の紙: (0,0)-(2,3)
        // 面積 = 2 × 3 = 6
        let rects = vec![(0, 0, 2, 3)];
        assert_eq!(solve(&rects), 6);
    }

    #[test]
    fn overlapping_rects() {
        // 2枚の重なる紙:
        // 紙1: (0,0)-(2,2) → 面積4
        // 紙2: (1,1)-(3,3) → 面積4
        //
        // 重なり: (1,1)-(2,2) → 面積1
        // 答え: 4 + 4 - 1 = 7
        let rects = vec![(0, 0, 2, 2), (1, 1, 3, 3)];
        assert_eq!(solve(&rects), 7);
    }

    #[test]
    fn no_overlap() {
        // 2枚の離れた紙:
        // 紙1: (0,0)-(1,1) → 面積1
        // 紙2: (2,2)-(3,3) → 面積1
        // 答え: 2
        let rects = vec![(0, 0, 1, 1), (2, 2, 3, 3)];
        assert_eq!(solve(&rects), 2);
    }

    #[test]
    fn complete_overlap() {
        // 完全に重なる2枚:
        // 両方 (0,0)-(2,2)
        // 面積 = 4（1回だけカウント）
        let rects = vec![(0, 0, 2, 2), (0, 0, 2, 2)];
        assert_eq!(solve(&rects), 4);
    }

    #[test]
    fn contained_rect() {
        // 包含関係:
        // 紙1: (0,0)-(4,4) → 大きい
        // 紙2: (1,1)-(3,3) → 紙1に含まれる
        //
        // 覆われる面積 = 4 × 4 = 16
        let rects = vec![(0, 0, 4, 4), (1, 1, 3, 3)];
        assert_eq!(solve(&rects), 16);
    }

    #[test]
    fn three_rects() {
        // 3枚の紙が複雑に重なる
        let rects = vec![(0, 0, 2, 2), (1, 1, 3, 3), (2, 0, 4, 2)];
        // 手計算で確認...
        let ans = solve(&rects);
        assert!(ans > 0);
    }
}
