// 030 - K Factors (★5)
// https://atcoder.jp/contests/typical90/tasks/typical90_ad
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// 数学の問題です。
//
// 整数 N と K が与えられます。
// 1 から N までの整数のうち、「素因数の種類数がちょうど K 個」のものを数えてください。
//
// 素因数の種類数とは:
// - 6 = 2 × 3 → 素因数は {2, 3} の2種類
// - 12 = 2² × 3 → 素因数は {2, 3} の2種類（べき乗は関係ない）
// - 30 = 2 × 3 × 5 → 素因数は {2, 3, 5} の3種類
// - 4 = 2² → 素因数は {2} の1種類
//
// 例: N = 10, K = 2
// - 6 = 2 × 3 → 2種類 ✓
// - 10 = 2 × 5 → 2種類 ✓
// 答え: 2
//
// ============================================================================
// 【解法：エラトステネスの篩の応用】
// ============================================================================
//
// 【アイデア】
//
// エラトステネスの篩は、素数を見つけるアルゴリズム。
// これを応用して「各数の素因数の種類数」を数える。
//
// 【アルゴリズム】
//
// 1. factor_count[i] = 0 で初期化
// 2. 各素数 p について:
//    - p, 2p, 3p, ... に対して factor_count を +1
// 3. factor_count[i] == K の数を数える
//
// 【なぜこれで正しい？】
//
// - 素数 p の倍数には p が素因数に含まれる
// - 各素数について +1 するので、最終的に素因数の種類数になる
// - 例: 6 は p=2 の倍数で +1、p=3 の倍数で +1 → factor_count[6] = 2
//
// 【素数の判定】
//
// factor_count[p] == 0 なら p は素数。
// （それより小さい素因数がないということ）
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - エラトステネスの篩: O(N log log N)
// - 合計: O(N log log N)
//
// ============================================================================

use proconio::input;

fn main() {
    input! {
        n: usize,
        k: usize,
    }
    println!("{}", solve(n, k));
}

fn solve(n: usize, k: usize) -> usize {
    // -------------------------------------------------------------------------
    // 【素因数の種類数を計算する配列】
    //
    // factor_count[i] = i の素因数の種類数
    // -------------------------------------------------------------------------
    let mut factor_count = vec![0usize; n + 1];

    // -------------------------------------------------------------------------
    // 【エラトステネスの篩の応用】
    //
    // 各素数 p について、その倍数に +1
    // -------------------------------------------------------------------------
    for p in 2..=n {
        if factor_count[p] == 0 {
            // -----------------------------------------------------------------
            // 【p は素数】
            //
            // factor_count[p] == 0 ということは、
            // p より小さい素数で p を割り切れるものがない。
            // つまり p は素数。
            // -----------------------------------------------------------------

            // -----------------------------------------------------------------
            // 【p の全ての倍数に +1】
            //
            // p, 2p, 3p, ... はすべて p を素因数に持つ
            // -----------------------------------------------------------------
            for multiple in (p..=n).step_by(p) {
                factor_count[multiple] += 1;
            }
        }
    }

    // -------------------------------------------------------------------------
    // 【素因数の種類数がちょうど K の数をカウント】
    //
    // 2 から N までの範囲で数える（1 は素因数を持たない）
    // -------------------------------------------------------------------------
    factor_count[2..=n].iter().filter(|&&c| c == k).count()
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn example1() {
        // N = 10, K = 2
        // 素因数2種類: 6 = 2×3, 10 = 2×5
        // 答え: 2
        assert_eq!(solve(10, 2), 2);
    }

    #[test]
    fn example2() {
        // N = 20, K = 2
        // 素因数2種類:
        // 6 = 2×3
        // 10 = 2×5
        // 12 = 2²×3 → 2種類
        // 14 = 2×7
        // 15 = 3×5
        // 18 = 2×3² → 2種類
        // 20 = 2²×5 → 2種類
        // 答え: 7
        assert_eq!(solve(20, 2), 7);
    }

    #[test]
    fn k_equals_1() {
        // K = 1: 素因数1種類 = 素数のべき乗
        //
        // 1〜10 で素因数1種類:
        // 2, 3, 4=2², 5, 7, 8=2³, 9=3²
        // 答え: 7
        assert_eq!(solve(10, 1), 7);
    }

    #[test]
    fn k_equals_3() {
        // K = 3: 素因数3種類
        //
        // 最小は 30 = 2 × 3 × 5
        // N = 29 なら該当なし
        // N = 30 なら 1個
        assert_eq!(solve(29, 3), 0);
        assert_eq!(solve(30, 3), 1);
    }

    #[test]
    fn large_k() {
        // K が大きすぎると該当なし
        // N = 10 で K = 5 → 不可能
        assert_eq!(solve(10, 5), 0);
    }

    #[test]
    fn k_equals_0() {
        // K = 0: 素因数0種類
        // 1 のみだが、範囲は 2〜N なので該当なし
        assert_eq!(solve(10, 0), 0);
    }

    #[test]
    fn factor_count_check() {
        // 個別に素因数の種類数を確認
        let n = 30;
        let mut factor_count = vec![0usize; n + 1];

        for p in 2..=n {
            if factor_count[p] == 0 {
                for multiple in (p..=n).step_by(p) {
                    factor_count[multiple] += 1;
                }
            }
        }

        assert_eq!(factor_count[2], 1);  // 2 = 素数
        assert_eq!(factor_count[6], 2);  // 6 = 2 × 3
        assert_eq!(factor_count[12], 2); // 12 = 2² × 3
        assert_eq!(factor_count[30], 3); // 30 = 2 × 3 × 5
    }
}
