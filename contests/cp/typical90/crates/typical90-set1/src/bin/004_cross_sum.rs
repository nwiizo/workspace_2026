// 004 - Cross Sum (★2)
// https://atcoder.jp/contests/typical90/tasks/typical90_d
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたはスプレッドシートの開発者です。
// H行 × W列のセルがあり、各セルに数値が入っています。
//
// 例えば、3×3のグリッド:
//
//    列0  列1  列2
//   +----+----+----+
// 行0|  1 |  2 |  3 |  ← 行の和 = 6
//   +----+----+----+
// 行1|  4 |  5 |  6 |  ← 行の和 = 15
//   +----+----+----+
// 行2|  7 |  8 |  9 |  ← 行の和 = 24
//   +----+----+----+
//     ↓    ↓    ↓
//    12   15   18  ← 列の和
//
// ユーザーから「各セルについて、同じ行と同じ列にある
// すべての数字の合計を表示したい」というリクエストが来ました。
//
// 例えば、セル(1,1)（値は5）の場合：
// - 同じ行(行1): 4, 5, 6
// - 同じ列(列1): 2, 5, 8
// - 自分自身(5)は1回だけカウント
// → 4 + 5 + 6 + 2 + 8 = 25
//
// これを H×W のすべてのセルについて計算してください。
//
// ============================================================================
// 【愚直な解法の問題点】
// ============================================================================
//
// 各マス(i,j)について、行と列を全部足すと：
// - 行の合計: O(W)
// - 列の合計: O(H)
// - 合計: O(H + W) × H × W マス = O(H²W + HW²)
//
// H = W = 2000 のとき、約 160億回の計算 → 時間切れ！
//
// ============================================================================
// 【効率的な解法：前計算（プリコンピュート）】
// ============================================================================
//
// 「同じ計算を何度もしている」ことに気づきましょう。
//
// 行の和は、同じ行のセルすべてで同じ値です。
// 列の和も、同じ列のセルすべてで同じ値です。
//
// なので、先に計算しておけばいい！
//
// 【ステップ1: 行の和を前計算】
//
// row_sum[i] = i行目のすべての要素の和
//
//   row_sum[0] = 1 + 2 + 3 = 6
//   row_sum[1] = 4 + 5 + 6 = 15
//   row_sum[2] = 7 + 8 + 9 = 24
//
// 【ステップ2: 列の和を前計算】
//
// col_sum[j] = j列目のすべての要素の和
//
//   col_sum[0] = 1 + 4 + 7 = 12
//   col_sum[1] = 2 + 5 + 8 = 15
//   col_sum[2] = 3 + 6 + 9 = 18
//
// 【ステップ3: 各マスの答えを計算】
//
// answer[i][j] = row_sum[i] + col_sum[j] - a[i][j]
//
// なぜ a[i][j] を引く？
// → 自分自身が「行の和」と「列の和」の両方に含まれるから！
//    2回足されてしまうので、1回分引きます。
//
// 例: セル(1,1)
//   row_sum[1] + col_sum[1] - a[1][1]
// = 15 + 15 - 5
// = 25 ✓
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - 行の和の前計算: O(H × W)
// - 列の和の前計算: O(H × W)
// - 各マスの答え計算: O(H × W)
// - 合計: O(H × W)
//
// H = W = 2000 でも 400万回の計算 → 余裕で間に合う！
//
// ============================================================================

use proconio::input;

fn main() {
    // -------------------------------------------------------------------------
    // 【入力の読み込み】
    //
    // proconio の2次元配列の読み込み:
    // a: [[i64; w]; h] は「i64型の要素がw個の配列」が h 個並んだもの
    // つまり a[i][j] で (i行, j列) の値にアクセスできる
    // -------------------------------------------------------------------------
    input! {
        h: usize,           // 行数
        w: usize,           // 列数
        a: [[i64; w]; h],   // H×W のグリッド
    }
    solve(h, w, &a);
}

fn solve(h: usize, w: usize, a: &[Vec<i64>]) {
    // -------------------------------------------------------------------------
    // 【行の和を前計算】
    //
    // a.iter() → 各行をイテレート
    // .map(|row| ...) → 各行に対して処理
    // row.iter().sum() → その行の全要素の合計
    // .collect() → Vec<i64> に変換
    //
    // 結果: row_sum[i] = i行目の全要素の和
    // -------------------------------------------------------------------------
    let row_sum: Vec<i64> = a.iter().map(|row| row.iter().sum()).collect();

    // -------------------------------------------------------------------------
    // 【列の和を前計算】
    //
    // 列方向は2次元配列では少し扱いにくい。
    // (0..w) で列インデックス j をイテレートして、
    // 各列について、全行の値を足し合わせる。
    //
    // (0..h).map(|i| a[i][j]).sum() は:
    // 「全ての行 i について a[i][j] を取り出して合計」
    // -------------------------------------------------------------------------
    let col_sum: Vec<i64> = (0..w).map(|j| (0..h).map(|i| a[i][j]).sum()).collect();

    // -------------------------------------------------------------------------
    // 【各マスの答えを計算して出力】
    //
    // 公式: answer[i][j] = row_sum[i] + col_sum[j] - a[i][j]
    //
    // 出力は行ごとにスペース区切り。
    // 各行を文字列として構築し、まとめて出力する。
    // -------------------------------------------------------------------------
    let mut result = Vec::with_capacity(h);
    for i in 0..h {
        let row: Vec<String> = (0..w)
            .map(|j| (row_sum[i] + col_sum[j] - a[i][j]).to_string())
            .collect();
        result.push(row.join(" "));
    }

    for line in result {
        println!("{}", line);
    }
}

// =============================================================================
// 【テスト】
//
// 実際の問題のサンプルケースでテストします。
// 手計算で答えを確認することで、理解を深めましょう。
// =============================================================================
#[cfg(test)]
mod tests {
    #[test]
    fn test_example1() {
        // 3×3 グリッド
        //
        //   +----+----+----+
        //   |  1 |  2 |  3 |  row_sum[0] = 6
        //   +----+----+----+
        //   |  4 |  5 |  6 |  row_sum[1] = 15
        //   +----+----+----+
        //   |  7 |  8 |  9 |  row_sum[2] = 24
        //   +----+----+----+
        //     12   15   18
        //    col_sum
        //
        // 各マスの答え:
        //   (0,0): 6 + 12 - 1 = 17
        //   (0,1): 6 + 15 - 2 = 19
        //   (0,2): 6 + 18 - 3 = 21
        //   (1,0): 15 + 12 - 4 = 23
        //   (1,1): 15 + 15 - 5 = 25
        //   ...

        let a = vec![vec![1, 2, 3], vec![4, 5, 6], vec![7, 8, 9]];
        let row_sum: Vec<i64> = a.iter().map(|row| row.iter().sum()).collect();
        let col_sum: Vec<i64> = (0..3).map(|j| (0..3).map(|i| a[i][j]).sum()).collect();

        assert_eq!(row_sum, vec![6, 15, 24]);
        assert_eq!(col_sum, vec![12, 15, 18]);

        // 個別のマスをチェック
        assert_eq!(row_sum[0] + col_sum[0] - a[0][0], 17);
        assert_eq!(row_sum[0] + col_sum[1] - a[0][1], 19);
        assert_eq!(row_sum[1] + col_sum[1] - a[1][1], 25);
    }

    #[test]
    fn test_1x1_grid() {
        // 1×1 のグリッド: 自分自身だけ
        // 答えは自分自身の値
        let a = vec![vec![42]];
        let row_sum: Vec<i64> = a.iter().map(|row| row.iter().sum()).collect();
        let col_sum: Vec<i64> = (0..1).map(|j| (0..1).map(|i| a[i][j]).sum()).collect();

        assert_eq!(row_sum[0] + col_sum[0] - a[0][0], 42);
    }

    #[test]
    fn test_row_vector() {
        // 1×3 のグリッド（行ベクトル）
        // [1, 2, 3]
        //
        // 各マスの答え（全部同じ行）:
        //   (0,0): 6 + 1 - 1 = 6
        //   (0,1): 6 + 2 - 2 = 6
        //   (0,2): 6 + 3 - 3 = 6
        let a = vec![vec![1, 2, 3]];
        let row_sum: Vec<i64> = a.iter().map(|row| row.iter().sum()).collect();
        let col_sum: Vec<i64> = (0..3).map(|j| (0..1).map(|i| a[i][j]).sum()).collect();

        assert_eq!(row_sum, vec![6]);
        assert_eq!(col_sum, vec![1, 2, 3]);
        assert_eq!(row_sum[0] + col_sum[0] - a[0][0], 6);
        assert_eq!(row_sum[0] + col_sum[1] - a[0][1], 6);
        assert_eq!(row_sum[0] + col_sum[2] - a[0][2], 6);
    }
}
