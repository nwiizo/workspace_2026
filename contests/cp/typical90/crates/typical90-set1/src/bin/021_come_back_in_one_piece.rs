// 021 - Come Back in One Piece (★5)
// https://atcoder.jp/contests/typical90/tasks/typical90_u
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたは交通ネットワークの分析者です。
// N 個の都市が M 本の一方通行道路でつながっています。
//
// 「往復可能」なペアを数えてください。
// つまり、都市 A から都市 B へ行けて、かつ B から A にも戻れる組み合わせです。
//
// 例:
//   0 → 1 → 2 → 0 （サイクル）
//
// このとき:
// - 0 から 1 へ行って戻れる（0→1, 1→2→0）
// - 0 から 2 へ行って戻れる（0→1→2, 2→0）
// - 1 から 2 へ行って戻れる（1→2, 2→0→1）
//
// 答え: 3 ペア
//
// ============================================================================
// 【解法：強連結成分分解（SCC）】
// ============================================================================
//
// 【強連結成分（SCC）とは？】
//
// 有向グラフで、互いに行き来できる頂点の最大集合。
//
// 例:
//   0 → 1 → 2
//   ↑       ↓
//   └───────┘
//
// {0, 1, 2} は1つの SCC（どこからでもどこへでも行ける）
//
// 【アルゴリズム: Kosaraju のアルゴリズム】
//
// 1. 元のグラフで DFS し、帰りがけ順を記録
// 2. 逆グラフを作る（全ての辺を反転）
// 3. 帰りがけ順の逆順で逆グラフを DFS → 各連結成分が SCC
//
// 【なぜこれで正しい？】
//
// - 帰りがけ順の逆順 ≒ トポロジカル順序
// - 逆グラフで探索すると、SCC 内の頂点だけ訪問できる
//
// 【ペア数の計算】
//
// SCC のサイズが s のとき:
// - ペア数 = s × (s-1) / 2 = C(s, 2)
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - DFS 2回: O(N + M)
// - 合計: O(N + M)
//
// ============================================================================

use proconio::input;
use proconio::marker::Usize1;

fn main() {
    input! {
        n: usize,
        m: usize,
        edges: [(Usize1, Usize1); m],
    }
    println!("{}", solve(n, &edges));
}

fn solve(n: usize, edges: &[(usize, usize)]) -> i64 {
    // -------------------------------------------------------------------------
    // 【隣接リスト構築】
    //
    // graph: 元のグラフ
    // rev_graph: 逆グラフ（全ての辺を反転）
    // -------------------------------------------------------------------------
    let mut graph = vec![vec![]; n];
    let mut rev_graph = vec![vec![]; n];
    for &(a, b) in edges {
        graph[a].push(b);
        rev_graph[b].push(a);
    }

    // -------------------------------------------------------------------------
    // 【1回目のDFS: 帰りがけ順を記録】
    //
    // 全ての頂点を DFS で訪問し、帰りがけ順（後退順）を記録する
    // -------------------------------------------------------------------------
    let mut order = Vec::with_capacity(n);
    let mut visited = vec![false; n];

    fn dfs1(v: usize, graph: &[Vec<usize>], visited: &mut [bool], order: &mut Vec<usize>) {
        visited[v] = true;
        for &next in &graph[v] {
            if !visited[next] {
                dfs1(next, graph, visited, order);
            }
        }
        order.push(v); // 帰りがけに記録
    }

    for v in 0..n {
        if !visited[v] {
            dfs1(v, &graph, &mut visited, &mut order);
        }
    }

    // -------------------------------------------------------------------------
    // 【2回目のDFS: 逆グラフで帰りがけ順の逆順に探索】
    //
    // これにより、各 SCC を識別し、サイズを記録する
    // -------------------------------------------------------------------------
    let mut component_id = vec![usize::MAX; n];
    let mut component_sizes = vec![];

    fn dfs2(
        v: usize,
        id: usize,
        rev_graph: &[Vec<usize>],
        component_id: &mut [usize],
        size: &mut usize,
    ) {
        component_id[v] = id;
        *size += 1;
        for &next in &rev_graph[v] {
            if component_id[next] == usize::MAX {
                dfs2(next, id, rev_graph, component_id, size);
            }
        }
    }

    for &v in order.iter().rev() {
        if component_id[v] == usize::MAX {
            let mut size = 0;
            dfs2(
                v,
                component_sizes.len(),
                &rev_graph,
                &mut component_id,
                &mut size,
            );
            component_sizes.push(size);
        }
    }

    // -------------------------------------------------------------------------
    // 【ペア数の計算】
    //
    // 各 SCC のサイズ s について、ペア数は s*(s-1)/2
    // -------------------------------------------------------------------------
    component_sizes
        .iter()
        .map(|&s| s as i64 * (s as i64 - 1) / 2)
        .sum()
}

