// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn example1() {
        // 3頂点、3辺: 0→1, 1→2, 2→0 (1つの SCC)
        // サイズ 3 → ペア数 = 3*2/2 = 3
        let edges = vec![(0, 1), (1, 2), (2, 0)];
        assert_eq!(solve(3, &edges), 3);
    }

    #[test]
    fn example2() {
        // 3頂点、2辺: 0→1, 1→2 (3つの SCC、各サイズ1)
        // ペア数 = 0
        let edges = vec![(0, 1), (1, 2)];
        assert_eq!(solve(3, &edges), 0);
    }

    #[test]
    fn two_sccs() {
        // 4頂点: 0↔1, 2↔3
        // SCC1: {0,1}, SCC2: {2,3}
        // ペア数 = 1 + 1 = 2
        let edges = vec![(0, 1), (1, 0), (2, 3), (3, 2)];
        assert_eq!(solve(4, &edges), 2);
    }

    #[test]
    fn single_vertex() {
        // 1頂点、0辺
        // ペア数 = 0
        let edges: Vec<(usize, usize)> = vec![];
        assert_eq!(solve(1, &edges), 0);
    }

    #[test]
    fn large_scc() {
        // 4頂点のサイクル
        // ペア数 = 4*3/2 = 6
        let edges = vec![(0, 1), (1, 2), (2, 3), (3, 0)];
        assert_eq!(solve(4, &edges), 6);
    }
}
