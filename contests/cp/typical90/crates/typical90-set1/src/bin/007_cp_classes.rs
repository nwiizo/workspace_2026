// 007 - CP Classes (★3)
// https://atcoder.jp/contests/typical90/tasks/typical90_g
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたは競技プログラミングスクールの運営者です。
// N 個のクラスがあり、それぞれ「推奨レーティング」A_i が決まっています。
//
// Q 人の生徒が入学してきました。
// 各生徒は「希望レーティング」B_j を持っています。
//
// 生徒は、自分の希望に最も近いクラスに入りたい。
// つまり、|A_i - B_j| が最小になるクラスを探します。
//
// 例:
//   クラス: [100, 300, 500, 800]
//   生徒の希望: 350
//
//   |100 - 350| = 250
//   |300 - 350| = 50  ← 最小！
//   |500 - 350| = 150
//   |800 - 350| = 450
//
//   この生徒の「不満度」は 50
//
// 各生徒について、最小の不満度を求めてください。
//
// ============================================================================
// 【愚直な解法の問題点】
// ============================================================================
//
// 各クエリで全クラスを探索すると：
// O(Q × N) = 10^5 × 10^5 = 10^10 → 時間切れ！
//
// ============================================================================
// 【効率的な解法：ソート + 二分探索】
// ============================================================================
//
// クラスのレーティングをソートしておくと、
// 「希望値に最も近いクラス」を素早く見つけられます。
//
// 【二分探索の考え方】
//
// ソート済み配列で target に最も近い値を探すには：
//
// 1. target 以上の最小値を二分探索で見つける（lower_bound）
// 2. その1つ前の要素（target 未満の最大値）も確認
// 3. 2つの候補のうち、差が小さい方を選ぶ
//
// 例: [100, 300, 500, 800], target = 350
//
// lower_bound(350) → index 2 (値 500)
// その1つ前 → index 1 (値 300)
//
// |500 - 350| = 150
// |300 - 350| = 50 ← こっちが近い！
//
// ============================================================================
// 【Rustでの二分探索】
// ============================================================================
//
// Rust では partition_point を使います。
//
// partition_point(|&x| x < target)
// → 「x < target を満たす要素の数」を返す
// → つまり「target 以上の最小のインデックス」
//
// C++ の lower_bound と同じ！
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - ソート: O(N log N)
// - 各クエリの二分探索: O(log N)
// - Q 回のクエリ: O(Q log N)
// - 合計: O((N + Q) log N)
//
// ============================================================================

use proconio::input;

fn main() {
    input! {
        n: usize,       // クラス数
        a: [i64; n],    // 各クラスの推奨レーティング
        q: usize,       // 生徒数
        b: [i64; q],    // 各生徒の希望レーティング
    }
    solve(n, &a, q, &b);
}

fn solve(_n: usize, a: &[i64], _q: usize, b: &[i64]) {
    // -------------------------------------------------------------------------
    // 【ソート】
    //
    // sort_unstable は sort より高速（安定ソートではないが、数値なら問題ない）
    // -------------------------------------------------------------------------
    let mut sorted_a = a.to_vec();
    sorted_a.sort_unstable();

    // -------------------------------------------------------------------------
    // 【各クエリを処理】
    // -------------------------------------------------------------------------
    for &target in b {
        // ---------------------------------------------------------------------
        // 【二分探索: target 以上の最小インデックスを見つける】
        //
        // partition_point(|&x| x < target):
        // - 条件 x < target を満たす要素の数を返す
        // - つまり sorted_a[pos] >= target となる最小の pos
        //
        // 例: [1, 3, 5, 7, 9], target = 4
        //     x < 4 を満たすのは [1, 3] の 2 個
        //     pos = 2, sorted_a[2] = 5 >= 4 ✓
        // ---------------------------------------------------------------------
        let pos = sorted_a.partition_point(|&x| x < target);

        let mut min_diff = i64::MAX;

        // ---------------------------------------------------------------------
        // 【候補1: target 以上の最小値】
        //
        // pos が配列の範囲内なら、sorted_a[pos] が候補
        // ---------------------------------------------------------------------
        if pos < sorted_a.len() {
            min_diff = min_diff.min((sorted_a[pos] - target).abs());
        }

        // ---------------------------------------------------------------------
        // 【候補2: target 未満の最大値】
        //
        // pos > 0 なら、sorted_a[pos - 1] が候補
        // (pos == 0 なら、target より小さい値は存在しない)
        // ---------------------------------------------------------------------
        if pos > 0 {
            min_diff = min_diff.min((sorted_a[pos - 1] - target).abs());
        }

        println!("{}", min_diff);
    }
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    #[test]
    fn test_partition_point() {
        let a: Vec<i64> = vec![1, 3, 5, 7, 9];

        // x < 4 を満たすのは [1, 3] → 2個
        // pos = 2, a[2] = 5 (4以上の最小)
        assert_eq!(a.partition_point(|&x| x < 4), 2);

        // x < 5 を満たすのは [1, 3] → 2個
        // pos = 2, a[2] = 5 (5以上の最小)
        assert_eq!(a.partition_point(|&x| x < 5), 2);

        // x < 6 を満たすのは [1, 3, 5] → 3個
        // pos = 3, a[3] = 7 (6以上の最小)
        assert_eq!(a.partition_point(|&x| x < 6), 3);

        // x < 0 を満たすものはない → 0個
        // pos = 0, a[0] = 1 (0以上の最小)
        assert_eq!(a.partition_point(|&x| x < 0), 0);

        // x < 100 を満たすのは全部 → 5個
        // pos = 5 (範囲外)
        assert_eq!(a.partition_point(|&x| x < 100), 5);
    }

    #[test]
    fn test_min_diff() {
        let sorted_a: Vec<i64> = vec![1, 3, 5, 7, 9];

        // target = 4: 候補は 3 と 5
        // |3 - 4| = 1, |5 - 4| = 1 → 最小は 1
        let target: i64 = 4;
        let pos = sorted_a.partition_point(|&x| x < target);
        let diff1 = (sorted_a[pos] - target).abs();
        let diff2 = (sorted_a[pos - 1] - target).abs();
        assert_eq!(diff1.min(diff2), 1);

        // target = 6: 候補は 5 と 7
        // |5 - 6| = 1, |7 - 6| = 1 → 最小は 1
        let target: i64 = 6;
        let pos = sorted_a.partition_point(|&x| x < target);
        assert_eq!((sorted_a[pos] - target).abs().min((sorted_a[pos - 1] - target).abs()), 1);
    }

    #[test]
    fn test_edge_smaller_than_all() {
        let sorted_a: Vec<i64> = vec![5, 10, 15];
        let target: i64 = 1;

        let pos = sorted_a.partition_point(|&x| x < target);
        // pos = 0, 左側に候補なし
        assert_eq!(pos, 0);
        // 最も近いのは 5
        assert_eq!((sorted_a[0] - target).abs(), 4);
    }

    #[test]
    fn test_edge_larger_than_all() {
        let sorted_a: Vec<i64> = vec![5, 10, 15];
        let target: i64 = 100;

        let pos = sorted_a.partition_point(|&x| x < target);
        // pos = 3 (範囲外), 右側に候補なし
        assert_eq!(pos, 3);
        // 最も近いのは 15
        assert_eq!((sorted_a[2] - target).abs(), 85);
    }
}
