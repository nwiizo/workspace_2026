// 006 - Smallest Subsequence (★5)
// https://atcoder.jp/contests/typical90/tasks/typical90_f
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたはスクラブル（単語ゲーム）の選手です。
// 手元に N 枚のアルファベットカードが並んでいます。
//
// ルール:
// - K 枚のカードを選んで単語を作る
// - カードは左から順番に並んでいる
// - 選んだカードの順番は変えられない（部分列として選ぶ）
// - 辞書順で最も小さい単語を作りたい
//
// 例: "bacba" から 3 枚選ぶ
//
//   位置: 0   1   2   3   4
//   文字: b   a   c   b   a
//
// 可能な選び方（順番を保って3文字選ぶ）:
// - "bac" (位置 0,1,2)
// - "bab" (位置 0,1,3)
// - "baa" (位置 0,1,4)  ← これが辞書順最小？
// - "bcb" (位置 0,2,3)
// - "bca" (位置 0,2,4)
// - "bba" (位置 0,3,4)
// - "acb" (位置 1,2,3)
// - "aca" (位置 1,2,4)
// - "aba" (位置 1,3,4)  ← これが辞書順最小！
// - "cba" (位置 2,3,4)
//
// 答え: "aba"
//
// ============================================================================
// 【辞書順とは？】
// ============================================================================
//
// 辞書に載っている順番のこと。
// - まず1文字目を比較
// - 同じなら2文字目を比較
// - ...
//
// 例: "aba" < "aca" < "baa"
//     (1文字目の a < a < b で、a同士なら2文字目で比較)
//
// ============================================================================
// 【貪欲法（グリーディ）のアイデア】
// ============================================================================
//
// 辞書順最小を作るには、できるだけ早い位置で小さい文字を選びたい。
//
// 【でも注意！】
// 「常に最小の文字を選ぶ」だけではダメ。
// 残りの文字で K 文字を完成できるか考える必要がある。
//
// 例: "za" から 2 文字選ぶ
// - 最小の 'a' を選ぶと、残りが無い！K=2 文字作れない
// - 仕方なく 'z' を選び、次に 'a' を選ぶ → "za"
//
// 【正しい貪欲法】
//
// 1文字目を選ぶとき:
// - 「この文字を選んでも、残りで K-1 文字作れるか？」をチェック
// - 作れる範囲内で、辞書順最小の文字を選ぶ
//
// 2文字目以降も同様に繰り返す。
//
// ============================================================================
// 【具体的なアルゴリズム】
// ============================================================================
//
// 【前計算】
// next[i][c] = 位置 i 以降で、文字 c が最初に現れる位置
//
// これがあると、「位置 i 以降で 'a' はどこ？」が O(1) でわかる。
//
// 【メインループ】
//
// 残り remaining 文字を選ぶとき:
// 1. 「ここで選んでも remaining-1 文字を後ろから選べる」限界位置を計算
//    limit = n - (remaining - 1) = n - remaining + 1
//
// 2. 位置 pos から limit 未満で、最初に見つかる 'a' を探す
// 3. なければ 'b', 'c', ... と探す
// 4. 見つかったら、その文字を選んで次へ
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - next 配列の前計算: O(N × 26)
// - メインループ: O(K × 26)
// - 合計: O(N × 26) = O(N)
//
// ============================================================================

use proconio::input;
use proconio::marker::Chars;

fn main() {
    input! {
        n: usize,   // 文字列の長さ
        k: usize,   // 選ぶ文字数
        s: Chars,   // 文字列（Vec<char> として読み込み）
    }
    println!("{}", solve(n, k, &s));
}

#[allow(clippy::needless_range_loop)]
fn solve(n: usize, k: usize, s: &[char]) -> String {
    // -------------------------------------------------------------------------
    // 【前計算: next配列】
    //
    // next[i][c] = 位置 i 以降で文字 c が最初に現れる位置
    //            = n (存在しない場合)
    //
    // 後ろから計算すると効率的:
    // - next[n][*] = n (終端を超えたらどの文字も存在しない)
    // - next[i][c] = next[i+1][c] を基本として、s[i] の文字だけ更新
    // -------------------------------------------------------------------------
    let mut next = vec![vec![n; 26]; n + 1];

    for i in (0..n).rev() {
        // まず i+1 の情報をコピー
        for c in 0..26 {
            next[i][c] = next[i + 1][c];
        }
        // 位置 i の文字を更新
        let c = (s[i] as u8 - b'a') as usize;
        next[i][c] = i;
    }

    // -------------------------------------------------------------------------
    // 【貪欲に文字を選ぶ】
    //
    // remaining: あと何文字選ぶ必要があるか
    // pos: 現在の探索開始位置
    // -------------------------------------------------------------------------
    let mut result = Vec::with_capacity(k);
    let mut pos = 0;

    for remaining in (1..=k).rev() {
        // remaining 文字を選ぶ必要がある
        // → この1文字を選んだ後、残り remaining-1 文字を選べる必要がある
        // → 選ぶ位置は n - (remaining - 1) 未満でなければならない
        let limit = n - remaining + 1;

        // 'a' から順に探す（辞書順最小を優先）
        for c in 0..26 {
            let char_pos = next[pos][c];
            if char_pos < limit {
                // この文字を選んでも残りを選べる！
                result.push((b'a' + c as u8) as char);
                pos = char_pos + 1; // 次はこの文字の次から探す
                break;
            }
        }
    }

    result.iter().collect()
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_example1() {
        // "abcdef" から 3文字
        // 辞書順最小は "abc"（先頭から順に選べばいい）
        let s: Vec<char> = "abcdef".chars().collect();
        assert_eq!(solve(6, 3, &s), "abc");
    }

    #[test]
    fn test_example2() {
        // "bacba" から 3文字
        //
        // 1文字目: 'a' を探す → 位置1にある
        //   位置1を選んでも残り4文字あるので2文字選べる → OK
        //
        // 2文字目: 位置2以降で 'a' を探す → 位置4にある
        //   位置4を選んでも残り1文字あるので1文字選べる？ → NO!
        //   limit = 5 - 1 = 4 なので、位置4は選べない
        //   次に 'b' を探す → 位置3にある → OK
        //
        // 3文字目: 位置4以降で 'a' を探す → 位置4にある → OK
        //
        // 結果: "aba"
        let s: Vec<char> = "bacba".chars().collect();
        assert_eq!(solve(5, 3, &s), "aba");
    }

    #[test]
    fn test_example3() {
        // "cba" から 2文字
        // 1文字目: 'a' は位置2にあるが、選ぶと残り0文字で1文字選べない
        //   'b' は位置1にある。選んでも残り1文字で1文字選べる → OK
        // 2文字目: 'a' は位置2にある → OK
        // 結果: "ba"
        let s: Vec<char> = "cba".chars().collect();
        assert_eq!(solve(3, 2, &s), "ba");
    }

    #[test]
    fn test_all_same() {
        // "aaaa" から 2文字 → "aa"
        let s: Vec<char> = "aaaa".chars().collect();
        assert_eq!(solve(4, 2, &s), "aa");
    }

    #[test]
    fn test_select_all() {
        // "abc" から 3文字 → "abc"
        let s: Vec<char> = "abc".chars().collect();
        assert_eq!(solve(3, 3, &s), "abc");
    }
}
