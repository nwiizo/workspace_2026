// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_factorial() {
        let (fact, _) = precompute_factorial(5);
        assert_eq!(fact[0], 1);  // 0! = 1
        assert_eq!(fact[1], 1);  // 1! = 1
        assert_eq!(fact[5], 120); // 5! = 120
    }

    #[test]
    fn test_comb() {
        let (fact, inv_fact) = precompute_factorial(10);

        // C(5, 2) = 10
        assert_eq!(comb(5, 2, &fact, &inv_fact), 10);

        // C(10, 3) = 120
        assert_eq!(comb(10, 3, &fact, &inv_fact), 120);

        // C(5, 0) = 1
        assert_eq!(comb(5, 0, &fact, &inv_fact), 1);

        // C(5, 5) = 1
        assert_eq!(comb(5, 5, &fact, &inv_fact), 1);
    }

    #[test]
    fn n_equals_3() {
        // N=3 の場合
        // K=1: C(3, 1) = 3  座席 {1}, {2}, {3}
        // K=2: C(2, 2) = 1  座席 {1, 3}
        // K=3: C(1, 3) = 0  不可能
        let (fact, inv_fact) = precompute_factorial(4);
        assert_eq!(comb(3, 1, &fact, &inv_fact), 3);
        assert_eq!(comb(2, 2, &fact, &inv_fact), 1);
        assert_eq!(comb(1, 3, &fact, &inv_fact), 0);
    }

    #[test]
    fn n_equals_5() {
        // N=5 の場合
        // K=1: C(5, 1) = 5
        // K=2: C(4, 2) = 6
        // K=3: C(3, 3) = 1
        let (fact, inv_fact) = precompute_factorial(6);
        assert_eq!(comb(5, 1, &fact, &inv_fact), 5);
        assert_eq!(comb(4, 2, &fact, &inv_fact), 6);
        assert_eq!(comb(3, 3, &fact, &inv_fact), 1);
    }
}
