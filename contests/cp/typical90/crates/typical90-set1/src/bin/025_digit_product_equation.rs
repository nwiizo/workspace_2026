// 025 - Digit Product Equation (★7)
// https://atcoder.jp/contests/typical90/tasks/typical90_y
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// 数学パズルです。
//
// f(m) を「m の各桁の積」と定義します（B進数で考える）。
//
// 例（10進数の場合）:
// - f(123) = 1 × 2 × 3 = 6
// - f(999) = 9 × 9 × 9 = 729
// - f(100) = 1 × 0 × 0 = 0  ← 0が含まれると0になる
//
// 問題: m + f(m) = N を満たす正の整数 m は何個あるか？
//
// 例: N = 11, B = 10
// - m = 10: f(10) = 0, 10 + 0 = 10 ≠ 11 ✗
// - m = 5:  f(5) = 5, 5 + 5 = 10 ≠ 11 ✗
// - 調べると... m が見つかれば答え
//
// ============================================================================
// 【解法：f(m) の候補を列挙】
// ============================================================================
//
// 【直接探索の問題点】
//
// N は最大 10^11 程度。
// 1 から N-1 まで全探索すると TLE。
//
// 【アイデア: f(m) の取りうる値は限られている】
//
// f(m) は「各桁の積」なので、f(m) の値は:
// - B進数なら、1 から B-1 の数の積でしか表せない
// - 10進数なら、1, 2, 3, ..., 9 の積
// - f(m) = 2^a × 3^b × 5^c × 7^d （10進数の場合）
//
// f(m) ≤ N なので、候補数は O(log N)^4 程度（数千個）
//
// 【逆算による検証】
//
// 1. f(m) の候補 f を列挙
// 2. m = N - f を計算
// 3. 実際に digit_product(m) == f か確認
//
// 例: N = 100, B = 10
// - f = 9 の場合: m = 100 - 9 = 91
//   digit_product(91) = 9 × 1 = 9 ✓
//   91 + 9 = 100 ✓
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - f(m) の候補数: O((log N)^4) ≈ 5000 程度
// - 各候補の検証: O(log N)
// - 合計: O((log N)^5)
//
// ============================================================================

use proconio::input;

fn main() {
    input! {
        n: i64,
        b: i64,
    }
    println!("{}", solve(n, b));
}

/// 各桁の積を計算（B進数）
///
/// 0が含まれる場合は0を返す。
/// m = 0 の場合も0を返す。
fn digit_product(mut m: i64, base: i64) -> i64 {
    if m == 0 {
        return 0;
    }
    let mut prod = 1i64;
    while m > 0 {
        let d = m % base;
        if d == 0 {
            return 0; // 0が含まれると積は0
        }
        prod *= d;
        m /= base;
    }
    prod
}

fn solve(n: i64, b: i64) -> usize {
    // -------------------------------------------------------------------------
    // 【f(m) の候補を列挙】
    //
    // f(m) は 1 から B-1 の数の積で表せる値のみ。
    // イテレーティブに列挙（再帰だとスタックオーバーフローの恐れ）。
    // -------------------------------------------------------------------------
    let mut candidates = vec![];

    // スタック: (現在の値, 次に使える最小の桁)
    // 同じ組み合わせを重複して数えないために、非減少順に桁を選ぶ
    let mut stack: Vec<(i64, i64)> = vec![(1, 1)];

    while let Some((current, min_digit)) = stack.pop() {
        if current > n {
            continue;
        }
        candidates.push(current);

        // 次の桁を選ぶ（min_digit から B-1 まで）
        for d in min_digit..b {
            // オーバーフロー対策
            if current > n / d {
                break;
            }
            stack.push((current * d, d));
        }
    }

    // -------------------------------------------------------------------------
    // 【各候補 f について検証】
    //
    // m = n - f を計算し、digit_product(m) == f かチェック
    // -------------------------------------------------------------------------
    let mut count = 0;
    for f in candidates {
        let m = n - f;
        if m >= 1 && digit_product(m, b) == f {
            count += 1;
        }
    }

    count
}

