// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_digit_product() {
        // 10進数での各桁の積
        assert_eq!(digit_product(123, 10), 6);   // 1*2*3
        assert_eq!(digit_product(100, 10), 0);   // 0が含まれる
        assert_eq!(digit_product(111, 10), 1);   // 1*1*1
        assert_eq!(digit_product(99, 10), 81);   // 9*9
        assert_eq!(digit_product(0, 10), 0);     // 0自体
    }

    #[test]
    fn example1() {
        // N=11, B=10
        // m=10: f(10)=0, 10+0=10≠11 ✗
        // 他に候補を探す...
        // 解答を確認
        assert_eq!(solve(11, 10), 1);
    }

    #[test]
    fn example2() {
        // N=100, B=10
        // m=91: f(91)=9, 91+9=100 ✓
        assert_eq!(digit_product(91, 10), 9);
        assert!(91 + 9 == 100);
    }

    #[test]
    fn small_base() {
        // B=2（2進数）
        // f(m) は 1 のみ（各桁は 0 or 1, 0があると積は0）
        // m + 1 = N → m = N - 1
        // m が全桁1なら f(m) = 1
        //
        // N=4, B=2: m=3=11(2進), f(3)=1, 3+1=4 ✓
        assert_eq!(solve(4, 2), 1);
    }

    #[test]
    fn n_equals_2() {
        // N=2, B=10
        // m + f(m) = 2
        // m=1: f(1)=1, 1+1=2 ✓
        assert_eq!(solve(2, 10), 1);
    }

    #[test]
    fn multiple_solutions() {
        // 複数の解がある場合をテスト
        // N=100, B=10 には複数の解がありうる
        let ans = solve(100, 10);
        assert!(ans >= 1);
    }

    #[test]
    fn n_is_large() {
        // 大きな N でも高速に動作することを確認
        // N = 10^9, B = 10
        let ans = solve(1_000_000_000, 10);
        // 具体的な答えは問題に依存、動作確認のみ
        assert!(ans >= 0);
    }
}
