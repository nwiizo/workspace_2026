// 005 - Restricted Digits (★7)
// https://atcoder.jp/contests/typical90/tasks/typical90_e
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたは暗号解読者です。
// 敵の暗号機は「特定の数字しか使えない」という制約があります。
//
// 例えば、暗号機が使える数字が {1, 4, 7} だけだとします。
// 暗号キーは「N桁の正整数で、Bで割り切れるもの」です。
//
// 【具体例】
// - N = 2桁
// - B = 7 で割り切れる
// - 使える数字 = {1, 4, 7}
//
// 可能な2桁の数: 11, 14, 17, 41, 44, 47, 71, 74, 77
// このうち7で割り切れるもの: 14 (14÷7=2), 77 (77÷7=11)
// 答え: 2個
//
// 【制約の厳しさ】
// - N は最大 10^18 桁まで！
// - 普通にシミュレーションすると絶対に間に合わない
//
// ============================================================================
// 【解法：動的計画法（DP）と行列累乗】
// ============================================================================
//
// 【ステップ1: DPで考える】
//
// dp[桁数][余り] = その状態になる方法の数
//
// 例: dp[2][0] = 「2桁で、Bで割った余りが0になる」数の個数
//
// 【遷移】
// 現在 i 桁目で余りが r の状態から、次の1桁に数字 d を追加すると：
// 新しい余り = (r × 10 + d) % B
//
// なぜ (r × 10 + d) なの？
// → 例えば「14」は 1×10 + 4 = 14
//   余り r の数に d を付けると、r×10 + d になる
//
// 【問題点】
// N = 10^18 のとき、1桁ずつ N 回遷移すると O(N) → 時間切れ！
//
// ============================================================================
// 【ステップ2: 行列で遷移を表現する】
// ============================================================================
//
// DP の遷移を行列の形で書いてみましょう。
//
// 状態ベクトル v = [dp[0], dp[1], ..., dp[B-1]]
// (v[r] = 余りが r である数の個数)
//
// 1桁追加する遷移は行列 M で表せます：
// M[r_next][r] = 「余り r から余り r_next に遷移できる数字の個数」
//
// 例: B = 3, 使える数字 = {1, 2}
//
// - 余り 0 + 数字 1 → 余り (0×10+1)%3 = 1
// - 余り 0 + 数字 2 → 余り (0×10+2)%3 = 2
// - 余り 1 + 数字 1 → 余り (1×10+1)%3 = 2
// - 余り 1 + 数字 2 → 余り (1×10+2)%3 = 0
// - 余り 2 + 数字 1 → 余り (2×10+1)%3 = 0
// - 余り 2 + 数字 2 → 余り (2×10+2)%3 = 1
//
// 行列 M:
//       from 0  from 1  from 2
// to 0 [   0      1       1   ]
// to 1 [   1      0       1   ]
// to 2 [   1      1       0   ]
//
// N-1 桁分の遷移 = M^(N-1) × (初期ベクトル)
//
// ============================================================================
// 【ステップ3: 行列累乗（繰り返し二乗法）】
// ============================================================================
//
// M^N を普通に計算すると N 回の行列積 → O(N × B³)
// しかし「繰り返し二乗法」を使うと O(log N × B³) に！
//
// 【繰り返し二乗法のアイデア】
//
// M^8 を計算したいとき：
// - M^1 = M
// - M^2 = M × M
// - M^4 = M^2 × M^2
// - M^8 = M^4 × M^4
//
// たった3回の行列積で M^8 が求まる！
//
// 一般に、指数 N を二進数で表して：
// N = 13 = 1101(2) = 8 + 4 + 1
// M^13 = M^8 × M^4 × M^1
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - 行列のサイズ: B × B
// - 行列積: O(B³)
// - 行列累乗: O(log N) 回の行列積
// - 合計: O(B³ log N)
//
// B = 1000, N = 10^18 でも約 60 回の行列積で済む！
//
// ============================================================================
// 【注意: 先頭の0】
// ============================================================================
//
// 「N桁の正整数」なので、先頭は0以外でなければなりません。
// 例: 007 は1桁ではなく、そもそも無効
//
// 解決方法:
// 1. 1桁目は0以外の数字のみで遷移を計算
// 2. 残りの N-1 桁は通常の行列累乗
//
// ============================================================================

use proconio::input;

const MOD: i64 = 1_000_000_007;

fn main() {
    input! {
        n: i64,         // 桁数（最大10^18！）
        b: usize,       // 割る数
        k: usize,       // 使える数字の個数
        c: [usize; k],  // 使える数字のリスト
    }
    println!("{}", solve(n, b, &c));
}

#[allow(clippy::needless_range_loop)]
fn solve(n: i64, b: usize, c: &[usize]) -> i64 {
    // -------------------------------------------------------------------------
    // 【遷移行列の構築】
    //
    // matrix[r_next][r] = 余り r から余り r_next への遷移回数
    //
    // 例: 余り r の数に数字 d を付けると、余り (r*10 + d) % b になる
    // -------------------------------------------------------------------------
    let mut matrix = vec![vec![0i64; b]; b];
    for r in 0..b {
        for &d in c {
            let r_next = (r * 10 + d) % b;
            matrix[r_next][r] = (matrix[r_next][r] + 1) % MOD;
        }
    }

    // -------------------------------------------------------------------------
    // 【先頭桁の処理】
    //
    // 先頭は0以外の数字のみ使用可能。
    // 0を除いた数字で1桁目の状態を計算。
    //
    // init[r] = 「1桁で余りがrになる」数の個数
    // -------------------------------------------------------------------------
    let c_nonzero: Vec<usize> = c.iter().copied().filter(|&d| d != 0).collect();

    let mut init = vec![0i64; b];
    for &d in &c_nonzero {
        let r = d % b;
        init[r] = (init[r] + 1) % MOD;
    }

    // -------------------------------------------------------------------------
    // 【1桁の場合】
    //
    // 遷移は不要。init[0] が答え。
    // -------------------------------------------------------------------------
    if n == 1 {
        return init[0];
    }

    // -------------------------------------------------------------------------
    // 【残りの N-1 桁の遷移】
    //
    // 行列累乗で M^(N-1) を計算し、初期ベクトルに掛ける。
    // -------------------------------------------------------------------------
    let trans = matrix_pow(&matrix, (n - 1) as u64, b);

    // 行列とベクトルの積: result = trans × init
    let mut result = vec![0i64; b];
    for i in 0..b {
        for j in 0..b {
            result[i] = (result[i] + trans[i][j] * init[j]) % MOD;
        }
    }

    // 答えは余り0になる個数
    result[0]
}

/// 行列の積 C = A × B
///
/// C[i][j] = Σ(k) A[i][k] × B[k][j]
fn matrix_mul(a: &[Vec<i64>], b_mat: &[Vec<i64>], size: usize) -> Vec<Vec<i64>> {
    let mut c = vec![vec![0i64; size]; size];
    for i in 0..size {
        for k in 0..size {
            // 枝刈り: A[i][k] が 0 なら、その行の計算は全部 0
            if a[i][k] == 0 {
                continue;
            }
            for j in 0..size {
                c[i][j] = (c[i][j] + a[i][k] * b_mat[k][j]) % MOD;
            }
        }
    }
    c
}

/// 行列累乗（繰り返し二乗法）
///
/// mat^exp を計算する。
///
/// 【アルゴリズム】
/// 1. result = 単位行列 I
/// 2. exp を二進数で見て、1が立っているビットで mat の累乗を掛ける
/// 3. 各ステップで mat を二乗していく
#[allow(clippy::needless_range_loop)]
fn matrix_pow(mat: &[Vec<i64>], mut exp: u64, size: usize) -> Vec<Vec<i64>> {
    // 単位行列（対角成分が1、それ以外が0）
    // I × M = M なので、掛け算の初期値として使える
    let mut result = vec![vec![0i64; size]; size];
    for i in 0..size {
        result[i][i] = 1;
    }

    let mut base = mat.to_vec();

    // 繰り返し二乗法
    while exp > 0 {
        if exp & 1 == 1 {
            // exp の最下位ビットが 1 なら、その累乗を result に掛ける
            result = matrix_mul(&result, &base, size);
        }
        // base を二乗
        base = matrix_mul(&base, &base, size);
        // exp を右シフト（÷2）
        exp >>= 1;
    }

    result
}

