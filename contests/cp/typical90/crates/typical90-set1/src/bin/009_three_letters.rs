// 009 - Three Letters (★2)
// https://atcoder.jp/contests/typical90/tasks/typical90_i
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたはパスワード生成システムの開発者です。
// N 個の単語リストがあり、それぞれの単語から先頭3文字を取り出します。
//
// ルール:
// - 異なる3つの単語を選ぶ
// - 各単語の先頭3文字を連結して、9文字のパスワードを作る
// - 辞書順で最大のパスワードを作りたい（セキュリティのため？）
//
// 例: ["abcd", "bcde", "cdef"]
//
// 先頭3文字: ["abc", "bcd", "cde"]
//
// 連結の候補:
// - abc + bcd + cde = "abcbcdcde"
// - abc + cde + bcd = "abccdebcd"
// - bcd + abc + cde = "bcdabccde"
// - ...
// - cde + bcd + abc = "cdebcdabc" ← これが辞書順最大！
//
// 【重要な気づき】
// 辞書順最大にするには、各パーツも辞書順で大きい方がいい。
// → 降順にソートして上位3つを選べばいい！
//
// ============================================================================
// 【解法】
// ============================================================================
//
// 1. 各文字列の先頭3文字を取り出す
// 2. 辞書順降順（大きい順）にソート
// 3. 上位3つを連結
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - 先頭3文字の取り出し: O(N)
// - ソート: O(N log N)
// - 連結: O(1)
// - 合計: O(N log N)
//
// ============================================================================

use proconio::input;

fn main() {
    input! {
        n: usize,           // 文字列の数
        s: [String; n],     // 文字列のリスト
    }
    println!("{}", solve(n, &s));
}

fn solve(n: usize, s: &[String]) -> String {
    // -------------------------------------------------------------------------
    // 【先頭3文字を取り出す】
    //
    // .chars().take(3) で最初の3文字を取得
    // .collect() で String に変換
    //
    // 3文字未満の場合は、あるだけの文字が取得される
    // -------------------------------------------------------------------------
    let mut prefixes: Vec<String> = s.iter().map(|t| t.chars().take(3).collect()).collect();

    // -------------------------------------------------------------------------
    // 【降順ソート】
    //
    // sort_by で比較関数を指定
    // |a, b| b.cmp(a) で降順（大きい順）になる
    //
    // 例: ["abc", "bcd", "cde"] → ["cde", "bcd", "abc"]
    // -------------------------------------------------------------------------
    prefixes.sort_by(|a, b| b.cmp(a));

    // -------------------------------------------------------------------------
    // 【上位3つを連結】
    //
    // format! マクロで文字列を連結
    // -------------------------------------------------------------------------
    if n >= 3 {
        format!("{}{}{}", prefixes[0], prefixes[1], prefixes[2])
    } else {
        prefixes.join("")
    }
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_example1() {
        let s = vec!["abcd".to_string(), "bcde".to_string(), "cdef".to_string()];
        // 先頭3文字: ["abc", "bcd", "cde"]
        // 降順: ["cde", "bcd", "abc"]
        // 連結: "cdebcdabc"
        assert_eq!(solve(3, &s), "cdebcdabc");
    }

    #[test]
    fn test_example2() {
        let s = vec![
            "zzz".to_string(),
            "yyy".to_string(),
            "xxx".to_string(),
            "www".to_string(),
        ];
        // 先頭3文字: ["zzz", "yyy", "xxx", "www"]
        // 降順: ["zzz", "yyy", "xxx", "www"]
        // 上位3つ: "zzzyyyxxx"
        assert_eq!(solve(4, &s), "zzzyyyxxx");
    }

    #[test]
    fn test_same_prefix() {
        let s = vec!["aaa".to_string(), "aab".to_string(), "aac".to_string()];
        // 降順: ["aac", "aab", "aaa"]
        // 連結: "aacaabaaa"
        assert_eq!(solve(3, &s), "aacaabaaa");
    }

    #[test]
    fn test_short_strings() {
        // 3文字未満の文字列
        let s = vec!["a".to_string(), "bb".to_string(), "ccc".to_string()];
        // 先頭3文字: ["a", "bb", "ccc"]
        // 降順: ["ccc", "bb", "a"]
        // 連結: "cccbba"
        assert_eq!(solve(3, &s), "cccbba");
    }
}
