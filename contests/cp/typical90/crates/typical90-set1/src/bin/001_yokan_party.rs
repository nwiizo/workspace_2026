// 001 - Yokan Party (★4)
// https://atcoder.jp/contests/typical90/tasks/typical90_a
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたはようかん屋さんです。
// 長さ L センチのようかんを K+1 個のピースに切り分けて、
// お客さんに配りたいと思っています。
//
// ようかんには N 箇所の「切れ目候補」があります。
// 切れ目の位置は配列 A で与えられます（左端からの距離）。
//
// 例えば、L=34cm のようかんに、8cm、13cm、26cm の位置に切れ目候補があるとします。
//
//   0cm                                                      34cm
//   |-------|-----|-------------|--------|
//           8    13            26
//
// ここから K 箇所を選んで切ると、K+1 個のピースができます。
//
// 【目標】
// 「一番小さいピースの長さ」をできるだけ大きくしたい！
//
// なぜこれが目標かというと、小さすぎるピースがあると
// そのお客さんがかわいそうだからです。
// 全員ができるだけ公平に、大きなピースをもらえるようにしたいのです。
//
// ============================================================================
// 【解法：答えで二分探索】
// ============================================================================
//
// この問題の鍵は「発想の転換」です。
//
// 普通に考えると「どこを切ればいいか？」と探索したくなりますが、
// それだと組み合わせが爆発してしまいます。
//
// そこで、こう考えます：
// 「もし『最小ピースが X cm 以上』という条件なら、K+1 個に分けられる？」
//
// この YES/NO 問題は、貪欲法（欲張り法）で簡単に判定できます：
// - 左から順番に見ていく
// - 前の切れ目から X cm 以上離れていたら、そこで切る
// - 最終的に K+1 個以上のピースが作れれば YES
//
// そして、X を変えながら探索します：
// - X が小さいと YES になりやすい（制約が緩いから）
// - X が大きいと NO になりやすい（制約が厳しいから）
//
// この性質を使って「二分探索」ができます！
// YES になる最大の X を効率的に見つけられるのです。
//
// ============================================================================
// 【二分探索とは？ - 数当てゲームのたとえ】
// ============================================================================
//
// 友達が 1〜100 の数字を思い浮かべていて、あなたが当てるゲームを想像してください。
// 友達は「もっと大きい」「もっと小さい」とだけ答えてくれます。
//
// 効率的な戦略は？
// 1. 「50？」 → 「もっと大きい」
// 2. 「75？」 → 「もっと小さい」
// 3. 「62？」 → 「もっと大きい」
// 4. 「68？」 → 「正解！」
//
// 毎回、候補を半分に絞れるので、100個の候補でも最大7回で当たります。
// これが二分探索の威力です。log2(100) ≈ 7 回！
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - 二分探索: O(log L) 回の判定
// - 各判定: O(N) で切れ目を順番に見る
// - 合計: O(N log L)
//
// N = 100,000、L = 1,000,000,000 でも余裕で間に合います。
// （log2(10億) ≈ 30 なので、約 300万回の操作）
//
// ============================================================================

use proconio::input;

fn main() {
    // -------------------------------------------------------------------------
    // 【入力の読み込み】
    // proconio は競プロ用の入力マクロです。
    // 標準入力から値を読み取って、変数に代入してくれます。
    // -------------------------------------------------------------------------
    input! {
        n: usize,       // 切れ目候補の数
        l: i64,         // ようかんの全長（センチメートル）
        k: usize,       // 何回切るか（K回切ると K+1 個のピースができる）
        a: [i64; n],    // 各切れ目候補の位置（左端からの距離）
    }
    println!("{}", solve(l, k, &a));
}

/// 「最小ピースの長さが min_len 以上」という条件で、K+1 個以上に分けられるか？
///
/// # 貪欲法（Greedy Algorithm）の考え方
///
/// 「欲張り」に、切れるところでどんどん切っていきます。
/// - 前の切れ目から min_len 以上離れていたら → 切る！
/// - そうでなければ → 切らない（スキップ）
///
/// なぜこれで正しいの？
/// → 早めに切っておいた方が、後で切る余裕ができるから。
///   「ここで切らずに後で切る」より「ここで切る」方が、
///   選択肢が広がる（または同じ）ことはあっても、狭まることはない。
fn can_divide(a: &[i64], l: i64, k: usize, min_len: i64) -> bool {
    // -------------------------------------------------------------------------
    // 【Rust文法解説：イテレータとfold】
    //
    // Rust ではループの代わりに「イテレータ」をよく使います。
    // これは関数型プログラミングのスタイルで、データの流れを
    // パイプラインのように記述できます。
    //
    // iter(): 配列の各要素を順番に取り出すイテレータを作る
    // chain(): 2つのイテレータを連結する（今回は右端 l を追加）
    // fold(): 畳み込み。初期値から始めて、各要素を処理しながら
    //         結果を「畳み込んで」いく。
    //
    // 例: [1, 2, 3].fold(0, |sum, x| sum + x)
    //     → 0 + 1 = 1 → 1 + 2 = 3 → 3 + 3 = 6
    // -------------------------------------------------------------------------
    let pieces = a
        .iter()
        .chain(std::iter::once(&l)) // 右端（ようかんの終点）を追加
        .fold((0usize, 0i64), |(count, prev), &pos| {
            // count: これまでに作ったピースの数
            // prev: 最後に切った位置
            // pos: 今見ている切れ目候補の位置

            if pos - prev >= min_len {
                // 前の切れ目から十分離れている → ここで切る！
                (count + 1, pos) // ピース数を+1、切った位置を更新
            } else {
                // まだ近すぎる → 切らない
                (count, prev) // 何も変えない
            }
        })
        .0; // タプルの最初の要素（ピース数）を取り出す

    // K回切ると K+1 個のピースができる。
    // pieces > k は「K+1 個以上作れた」という意味。
    pieces > k
}

/// メインの解法：二分探索で答えを見つける
fn solve(l: i64, k: usize, a: &[i64]) -> i64 {
    // -------------------------------------------------------------------------
    // 【二分探索の実装】
    //
    // lo: 「ここまでは OK」と分かっている境界
    // hi: 「ここからは NG」と分かっている境界
    //
    // 最初は何も分からないので：
    // - lo = 0（長さ0なら絶対OK）
    // - hi = l + 1（全長を超えたら絶対NG）
    //
    // 毎回、中間点 mid を試して、境界を狭めていきます。
    // 最終的に lo と hi が隣り合ったら終了。答えは lo。
    // -------------------------------------------------------------------------
    let (mut lo, mut hi) = (0i64, l + 1);

    while hi - lo > 1 {
        let mid = lo + (hi - lo) / 2; // オーバーフロー対策の書き方

        if can_divide(a, l, k, mid) {
            // mid で OK → もっと大きくできるかも！
            lo = mid; // OK の境界を広げる
        } else {
            // mid で NG → 大きすぎた
            hi = mid; // NG の境界を狭める
        }
    }

    lo // OK の最大値が答え
}

