// 【テスト】
// =============================================================================
//
// Rust では #[test] をつけた関数がテストになります。
// `cargo test` で実行できます。
//
// テストは「コードが正しく動くことの証拠」であり、
// 競プロでは「サンプルケースが通ること」の確認に使います。
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn example1() {
        // L=34, K=1（1回切って2ピースに分ける）
        // 切れ目候補: 8, 13, 26
        //
        // 13の位置で切ると: [0-13], [13-34] = 13cm と 21cm → 最小13cm
        // 8の位置で切ると: [0-8], [8-34] = 8cm と 26cm → 最小8cm
        // 26の位置で切ると: [0-26], [26-34] = 26cm と 8cm → 最小8cm
        //
        // 13cm が最大！
        assert_eq!(solve(34, 1, &[8, 13, 26]), 13);
    }

    #[test]
    fn example2() {
        // L=34, K=2（2回切って3ピースに分ける）
        // 切れ目候補: 8, 13, 26
        //
        // 8と26で切ると: [0-8], [8-26], [26-34] = 8cm, 18cm, 8cm → 最小8cm
        // 8と13で切ると: [0-8], [8-13], [13-34] = 8cm, 5cm, 21cm → 最小5cm
        // 13と26で切ると: [0-13], [13-26], [26-34] = 13cm, 13cm, 8cm → 最小8cm
        //
        // 8cm が最大！
        assert_eq!(solve(34, 2, &[8, 13, 26]), 8);
    }

    #[test]
    fn edge_case_single_cut() {
        // シンプルなケース：ちょうど真ん中で切る
        // L=10, K=1, 切れ目候補: 5
        // 5で切ると: [0-5], [5-10] = 5cm, 5cm → 最小5cm
        assert_eq!(solve(10, 1, &[5]), 5);
    }
}
