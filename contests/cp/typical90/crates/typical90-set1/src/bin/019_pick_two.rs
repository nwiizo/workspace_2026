// 019 - Pick Two (★6)
// https://atcoder.jp/contests/typical90/tasks/typical90_s
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// ボールが 2N 個、一列に並んでいます。
// 各ボールには数字が書かれています。
//
// ゲームのルール:
// 1. 隣り合う2個のボールを選んで取り除く
// 2. そのとき、2つの数字の差の絶対値がスコアに加算される
// 3. これを N 回繰り返して、全てのボールを取り除く
//
// スコアの最小値を求めてください。
//
// 例: [1, 3, 2, 4]
//
// 戦略1: (3,2)→(1,4)
//   |3-2| = 1、残り[1,4]
//   |1-4| = 3
//   合計: 4
//
// 戦略2: 両端ペア(1,4) + 内側(3,2)
//   区間DPの考え方: dp[0][4] = |a[0]-a[3]| + dp[1][3]
//                            = |1-4| + |3-2|
//                            = 3 + 1 = 4
//
// ============================================================================
// 【解法：区間DP】
// ============================================================================
//
// 【区間DPとは？】
//
// 区間 [l, r) を「部分問題」として考える DP。
// 小さい区間から順に解いて、大きい区間の答えを構成する。
//
// 【状態の定義】
//
// dp[l][r] = 区間 [l, r) のボールを全て取り除くときのコストの最小値
//
// 【遷移】
//
// 区間 [l, r) を処理する方法:
//
// 1. 両端をペアにする: a[l] と a[r-1] をペアにする
//    コスト = |a[l] - a[r-1]| + dp[l+1][r-1]
//
// 2. 区間を分割する: [l, mid) と [mid, r) に分ける
//    コスト = dp[l][mid] + dp[mid][r]
//
// 【なぜ両端ペアを考える？】
//
// 隣接ペアしか取れないが、「最終的に両端がペアになる」ケースがある。
// その間のボールを先に全部取り除けば、両端が隣接するから。
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - 状態数: O(N²)
// - 各状態の遷移: O(N)
// - 合計: O(N³)
//
// N ≤ 200 なので、8×10^6 程度で間に合う。
//
// ============================================================================

use proconio::input;

fn main() {
    input! {
        n: usize,
        a: [i64; 2 * n],
    }
    println!("{}", solve(&a));
}

#[allow(clippy::needless_range_loop)]
fn solve(a: &[i64]) -> i64 {
    let n = a.len();

    // -------------------------------------------------------------------------
    // 【DP配列の初期化】
    //
    // dp[l][r] = 区間 [l, r) を処理するコスト
    // 初期値: i64::MAX（未計算）
    // -------------------------------------------------------------------------
    let mut dp = vec![vec![i64::MAX; n + 1]; n + 1];

    // -------------------------------------------------------------------------
    // 【基底ケース: 長さ0の区間】
    //
    // ボールがなければコスト0
    // -------------------------------------------------------------------------
    for i in 0..=n {
        dp[i][i] = 0;
    }

    // -------------------------------------------------------------------------
    // 【区間DPのメインループ】
    //
    // 長さ2から順に計算（長さ1は奇数なので処理不要）
    // -------------------------------------------------------------------------
    for len in (2..=n).step_by(2) {
        for l in 0..=n - len {
            let r = l + len;

            // -----------------------------------------------------------------
            // 【遷移1: 両端をペアにする】
            //
            // a[l] と a[r-1] をペアにして、残り [l+1, r-1) を処理
            // -----------------------------------------------------------------
            let cost1 = (a[l] - a[r - 1]).abs() + dp[l + 1][r - 1];
            dp[l][r] = dp[l][r].min(cost1);

            // -----------------------------------------------------------------
            // 【遷移2: 区間を分割する】
            //
            // [l, mid) と [mid, r) に分けて、それぞれ処理
            // 分割点 mid は偶数刻み（各部分区間が偶数長になるため）
            // -----------------------------------------------------------------
            for mid in (l + 2..r).step_by(2) {
                if dp[l][mid] != i64::MAX && dp[mid][r] != i64::MAX {
                    dp[l][r] = dp[l][r].min(dp[l][mid] + dp[mid][r]);
                }
            }
        }
    }

    dp[0][n]
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn example1() {
        // [1, 2] → ペア(1,2) で |1-2| = 1
        assert_eq!(solve(&[1, 2]), 1);
    }

    #[test]
    fn example2() {
        // [1, 3, 2, 4]
        //
        // 両端ペア: |1-4| = 3, 残り[3,2] → |3-2| = 1
        // 合計: 4
        //
        // 分割: [1,3] + [2,4] = |1-3| + |2-4| = 2 + 2 = 4
        //
        // どちらも4で同じ
        assert_eq!(solve(&[1, 3, 2, 4]), 4);
    }

    #[test]
    fn sorted_array() {
        // [1, 2, 3, 4]
        //
        // 両端ペア: |1-4| = 3, 残り[2,3] → |2-3| = 1 → 合計4
        // 分割: [1,2] + [3,4] = 1 + 1 = 2 ← これが最小
        assert_eq!(solve(&[1, 2, 3, 4]), 2);
    }

    #[test]
    fn same_values() {
        // [5, 5, 5, 5] → どうペアにしても差は0
        assert_eq!(solve(&[5, 5, 5, 5]), 0);
    }

    #[test]
    fn six_elements() {
        // [1, 5, 2, 6, 3, 7]
        // 様々な分割を試して最小を求める
        let a = vec![1, 5, 2, 6, 3, 7];
        let ans = solve(&a);
        // 手計算で確認: 分割 [1,5][2,6][3,7] = 4+4+4 = 12
        // 両端 |1-7|=6 + [5,2,6,3] = 6 + ?
        assert!(ans > 0);
    }
}
