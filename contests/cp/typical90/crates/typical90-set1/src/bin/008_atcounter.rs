// 008 - AtCounter (★4)
// https://atcoder.jp/contests/typical90/tasks/typical90_h
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたは「atcoder」という文字列を探す宝探しをしています。
// 長い文字列 S の中から、順番に文字を拾って「atcoder」を作りたい。
//
// ただし、連続している必要はありません。
// 順番さえ合っていれば、間に他の文字があっても OK。
//
// これを「部分列（subsequence）」と言います。
//
// 例: S = "aattccooddeerr"
//
// 1番目の 'a' を選ぶか、2番目の 'a' を選ぶか
// 1番目の 't' を選ぶか、2番目の 't' を選ぶか
// ... という選び方がそれぞれ 2 通りずつ
//
// 合計: 2^7 = 128 通り
//
// 【注意】
// 答えが非常に大きくなる可能性があるので、
// 10^9 + 7 で割った余りを求めます。
//
// ============================================================================
// 【解法：動的計画法（DP）】
// ============================================================================
//
// 【状態の定義】
//
// dp[i] = 「atcoder」の最初の i 文字を作る方法の数
//
// つまり:
// - dp[0] = 空文字列を作る方法 = 1通り（何も選ばない）
// - dp[1] = "a" を作る方法の数
// - dp[2] = "at" を作る方法の数
// - dp[3] = "atc" を作る方法の数
// - ...
// - dp[7] = "atcoder" を作る方法の数 ← これが答え！
//
// ============================================================================
// 【遷移の考え方】
// ============================================================================
//
// 文字列 S を左から順番に見ていきます。
// 現在見ている文字が c のとき:
//
// 「atcoder」の i 番目の文字が c と一致するなら:
// - c を「使う」選択肢が増える
// - dp[i+1] += dp[i]
//
// 例: S = "axa", target = "atcoder"
//
// 初期: dp = [1, 0, 0, 0, 0, 0, 0, 0]
//
// S[0] = 'a' (target[0] = 'a' と一致)
//   dp[1] += dp[0] → dp = [1, 1, 0, 0, 0, 0, 0, 0]
//
// S[1] = 'x' (target のどこにも一致しない)
//   何も変化なし
//
// S[2] = 'a' (target[0] = 'a' と一致)
//   dp[1] += dp[0] → dp = [1, 2, 0, 0, 0, 0, 0, 0]
//
// 結果: "a" を作る方法は 2 通り（1番目か3番目の 'a' を選ぶ）
//
// ============================================================================
// 【重要: 後ろから更新する理由】
// ============================================================================
//
// もし前から更新すると、同じ文字を何度も使ってしまう！
//
// 悪い例: target = "aa", S = "a"
//
// 前から更新:
//   dp[1] += dp[0] → dp = [1, 1, 0]
//   dp[2] += dp[1] → dp = [1, 1, 1]  ← 間違い！
//
// 後ろから更新:
//   dp[2] += dp[1] → dp = [1, 0, 0] (dp[1] = 0 なので変化なし)
//   dp[1] += dp[0] → dp = [1, 1, 0]  ← 正しい！
//
// 後ろから更新することで、「今見ている文字」を複数回使うことを防げます。
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - S の各文字について O(7) の処理
// - 合計: O(N × 7) = O(N)
//
// ============================================================================

use proconio::input;
use proconio::marker::Chars;

const MOD: i64 = 1_000_000_007;

fn main() {
    input! {
        _n: usize,  // 文字列の長さ（使わないが入力にある）
        s: Chars,   // 文字列
    }
    println!("{}", solve(&s));
}

fn solve(s: &[char]) -> i64 {
    // -------------------------------------------------------------------------
    // 【ターゲット文字列】
    // -------------------------------------------------------------------------
    let target: Vec<char> = "atcoder".chars().collect();

    // -------------------------------------------------------------------------
    // 【DP配列の初期化】
    //
    // dp[i] = target の最初の i 文字を作る方法の数
    // dp[0] = 1 (空文字列を作る方法は 1 通り)
    //
    // 固定長配列 [0i64; 8] を使うことで、ヒープ確保を避けて高速化
    // -------------------------------------------------------------------------
    let mut dp = [0i64; 8];
    dp[0] = 1;

    // -------------------------------------------------------------------------
    // 【メインループ: S の各文字を順番に処理】
    // -------------------------------------------------------------------------
    for &c in s {
        // ---------------------------------------------------------------------
        // 【後ろから更新】
        //
        // i = 6, 5, 4, 3, 2, 1, 0 の順に見る
        // target[i] と c が一致したら、dp[i+1] に dp[i] を足す
        // ---------------------------------------------------------------------
        for i in (0..7).rev() {
            if c == target[i] {
                dp[i + 1] = (dp[i + 1] + dp[i]) % MOD;
            }
        }
    }

    // dp[7] = "atcoder" を作る方法の数
    dp[7]
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_example1() {
        // "atcoder" → 1通り（そのまま全部使う）
        let s: Vec<char> = "atcoder".chars().collect();
        assert_eq!(solve(&s), 1);
    }

    #[test]
    fn test_example2() {
        // "aattccooddeerr"
        // 各文字が 2 つずつあるので、2^7 = 128 通り
        let s: Vec<char> = "aattccooddeerr".chars().collect();
        assert_eq!(solve(&s), 128);
    }

    #[test]
    fn test_no_match() {
        // "xyz" → 0通り（'a' がない）
        let s: Vec<char> = "xyz".chars().collect();
        assert_eq!(solve(&s), 0);
    }

    #[test]
    fn test_partial_match() {
        // "atc" → 0通り（"atcoder" を完成できない）
        let s: Vec<char> = "atc".chars().collect();
        assert_eq!(solve(&s), 0);
    }

    #[test]
    fn test_many_a() {
        // "aaatcoder" → 3通り（どの 'a' を使うか）
        let s: Vec<char> = "aaatcoder".chars().collect();
        assert_eq!(solve(&s), 3);
    }

    #[test]
    fn test_dp_update_order() {
        // "aa" で target = "aa" を作る
        // 答えは 1 通り（両方使う）
        // これが正しく動くには、後ろから更新が必要
        let target: Vec<char> = "aa".chars().collect();
        let s: Vec<char> = "aa".chars().collect();

        let mut dp = [0i64; 3];
        dp[0] = 1;

        for &c in &s {
            for i in (0..2).rev() {
                if c == target[i] {
                    dp[i + 1] = dp[i + 1] + dp[i];
                }
            }
        }

        assert_eq!(dp[2], 1);
    }
}
