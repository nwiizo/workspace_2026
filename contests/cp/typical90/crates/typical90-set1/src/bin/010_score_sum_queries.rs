#[cfg(test)]
mod tests {
    #[test]
    fn test_cumulative_sum() {
        // 生徒: (1, 10), (2, 20), (1, 30), (2, 40), (1, 50)
        let students = vec![(1, 10), (2, 20), (1, 30), (2, 40), (1, 50)];
        let n = students.len();

        let mut prefix1 = vec![0i64; n + 1];
        let mut prefix2 = vec![0i64; n + 1];

        for (i, &(class, score)) in students.iter().enumerate() {
            prefix1[i + 1] = prefix1[i];
            prefix2[i + 1] = prefix2[i];
            if class == 1 {
                prefix1[i + 1] += score;
            } else {
                prefix2[i + 1] += score;
            }
        }

        // 累積和を確認
        // prefix1: [0, 10, 10, 40, 40, 90]  (クラス1: 10, 30, 50)
        // prefix2: [0, 0, 20, 20, 60, 60]   (クラス2: 20, 40)
        assert_eq!(prefix1, vec![0, 10, 10, 40, 40, 90]);
        assert_eq!(prefix2, vec![0, 0, 20, 20, 60, 60]);

        // 区間[1, 5]: クラス1: 90, クラス2: 60
        assert_eq!(prefix1[5] - prefix1[0], 90);
        assert_eq!(prefix2[5] - prefix2[0], 60);

        // 区間[2, 4]: クラス1: 30, クラス2: 60
        assert_eq!(prefix1[4] - prefix1[1], 30);
        assert_eq!(prefix2[4] - prefix2[1], 60);
    }

    #[test]
    fn test_single_query() {
        let students = vec![(1, 100), (2, 200)];
        let n = 2;

        let mut prefix1 = vec![0i64; n + 1];
        let mut prefix2 = vec![0i64; n + 1];

        for (i, &(class, score)) in students.iter().enumerate() {
            prefix1[i + 1] = prefix1[i];
            prefix2[i + 1] = prefix2[i];
            if class == 1 {
                prefix1[i + 1] += score;
            } else {
                prefix2[i + 1] += score;
            }
        }

        // 区間[1, 1]: 生徒1だけ
        assert_eq!(prefix1[1] - prefix1[0], 100);
        assert_eq!(prefix2[1] - prefix2[0], 0);

        // 区間[2, 2]: 生徒2だけ
        assert_eq!(prefix1[2] - prefix1[1], 0);
        assert_eq!(prefix2[2] - prefix2[1], 200);
    }
}
