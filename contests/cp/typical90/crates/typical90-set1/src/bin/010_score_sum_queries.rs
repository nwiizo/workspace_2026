// 010 - Score Sum Queries (★2)
// https://atcoder.jp/contests/typical90/tasks/typical90_j
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたは学校の成績管理システムを作っています。
// N 人の生徒がいて、各生徒は:
// - クラス1 または クラス2 に所属
// - テストの点数を持っている
//
// Q 個のクエリが来ます:
// 「生徒 L 番から R 番までで、クラス1とクラス2の点数合計をそれぞれ教えて」
//
// 例:
//   生徒1: クラス1, 点数10
//   生徒2: クラス2, 点数20
//   生徒3: クラス1, 点数30
//   生徒4: クラス2, 点数40
//   生徒5: クラス1, 点数50
//
// クエリ「2番から4番まで」:
// - クラス1: 生徒3の30点
// - クラス2: 生徒2の20点 + 生徒4の40点 = 60点
// 答え: "30 60"
//
// ============================================================================
// 【愚直な解法の問題点】
// ============================================================================
//
// 各クエリで L から R まで全部足すと:
// O(Q × N) = 10^5 × 10^5 = 10^10 → 時間切れ！
//
// ============================================================================
// 【効率的な解法：累積和（Prefix Sum）】
// ============================================================================
//
// 【累積和とは？】
//
// 「最初から i 番目までの合計」を事前に計算しておく。
// すると、区間 [L, R] の合計は引き算で O(1) で求まる！
//
// prefix[R] - prefix[L-1] = 区間 [L, R] の合計
//
// 例: a = [10, 20, 30, 40, 50]
//
// prefix = [0, 10, 30, 60, 100, 150]
//         (0) (a1) (a1+a2) (a1+a2+a3) ...
//
// 区間 [2, 4] の合計:
// = prefix[4] - prefix[1]
// = 100 - 10
// = 90 (= 20 + 30 + 40)
//
// 【この問題での応用】
//
// クラスが2つあるので、累積和も2つ用意する！
// - prefix1[i] = 最初の i 人のうち、クラス1 の点数合計
// - prefix2[i] = 最初の i 人のうち、クラス2 の点数合計
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - 累積和の前計算: O(N)
// - 各クエリの処理: O(1)
// - Q 回のクエリ: O(Q)
// - 合計: O(N + Q)
//
// ============================================================================

use proconio::input;

fn main() {
    input! {
        n: usize,
        students: [(usize, i64); n],        // (class, score)
        q: usize,
        queries: [(usize, usize); q],       // (l, r) 1-indexed
    }
    solve(n, &students, q, &queries);
}

fn solve(n: usize, students: &[(usize, i64)], _q: usize, queries: &[(usize, usize)]) {
    // -------------------------------------------------------------------------
    // 【累積和の構築】
    //
    // prefix1[i] = 生徒 1 から i までの、クラス1 の点数合計
    // prefix2[i] = 生徒 1 から i までの、クラス2 の点数合計
    //
    // prefix[0] = 0 (誰もいない場合)
    // -------------------------------------------------------------------------
    let mut prefix1 = vec![0i64; n + 1];
    let mut prefix2 = vec![0i64; n + 1];

    for (i, &(class, score)) in students.iter().enumerate() {
        // まず前の値をコピー
        prefix1[i + 1] = prefix1[i];
        prefix2[i + 1] = prefix2[i];

        // 該当するクラスに点数を加算
        if class == 1 {
            prefix1[i + 1] += score;
        } else {
            prefix2[i + 1] += score;
        }
    }

    // -------------------------------------------------------------------------
    // 【クエリ処理】
    //
    // 区間 [L, R] の合計 = prefix[R] - prefix[L-1]
    //
    // 注意: クエリは 1-indexed で与えられる
    // -------------------------------------------------------------------------
    for &(l, r) in queries {
        let sum1 = prefix1[r] - prefix1[l - 1];
        let sum2 = prefix2[r] - prefix2[l - 1];
        println!("{} {}", sum1, sum2);
    }
}

