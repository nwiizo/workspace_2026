// 024 - Select +/- One (★2)
// https://atcoder.jp/contests/typical90/tasks/typical90_x
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// 数列 A があり、これを数列 B に変えたい。
//
// 1回の操作:
// - どれか1つの要素を選んで +1 または -1 する
//
// 「ちょうど K 回」の操作で A を B に変えられるか判定してください。
//
// 例1: A = [3, 4, 1], B = [5, 2, 3], K = 6
//
// 必要な変更:
// - A[0]: 3 → 5 = +2 (2回)
// - A[1]: 4 → 2 = -2 (2回)
// - A[2]: 1 → 3 = +2 (2回)
// - 合計: 6回
//
// K = 6 なので、ちょうど使い切れる → Yes
//
// 例2: A = [1], B = [2], K = 2
//
// 必要な変更: +1 (1回)
// K = 2 だが、1回で終わる。
// 余り1回を使うには +1 -1 する必要があるが、これは偶数回のペアでないと
// 元に戻らない。余り1は奇数なので無理 → No
//
// ============================================================================
// 【解法】
// ============================================================================
//
// 【必要な操作回数】
//
// diff = Σ |A_i - B_i|
//
// 【条件】
//
// 1. diff ≤ K: 最低限の操作で足りる
// 2. (K - diff) が偶数: 余りの操作を「+1 と -1 のペア」で消費できる
//
// 【なぜ偶数？】
//
// 余った操作は「どこかを +1 して、また -1 する」という無駄な動きで消費する。
// +1 と -1 で2回使うので、余りは偶数でないといけない。
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - 差の合計: O(N)
// - 判定: O(1)
// - 合計: O(N)
//
// ============================================================================

use proconio::input;

fn main() {
    input! {
        n: usize,
        k: i64,
        a: [i64; n],
        b: [i64; n],
    }

    if solve(&a, &b, k) {
        println!("Yes");
    } else {
        println!("No");
    }
}

fn solve(a: &[i64], b: &[i64], k: i64) -> bool {
    // -------------------------------------------------------------------------
    // 【必要な操作回数を計算】
    //
    // 各要素の差の絶対値の合計
    // -------------------------------------------------------------------------
    let diff: i64 = a.iter().zip(b.iter()).map(|(x, y)| (x - y).abs()).sum();

    // -------------------------------------------------------------------------
    // 【判定】
    //
    // 1. 必要な回数以上あるか: diff ≤ k
    // 2. 余りが偶数か: (k - diff) % 2 == 0
    // -------------------------------------------------------------------------
    diff <= k && (k - diff) % 2 == 0
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn example1() {
        // A=[3,4,1], B=[5,2,3]
        // diff = |3-5| + |4-2| + |1-3| = 2+2+2 = 6
        // K=6, diff=6, 余り0 → Yes
        assert!(solve(&[3, 4, 1], &[5, 2, 3], 6));
    }

    #[test]
    fn example2() {
        // A=[1], B=[2]
        // diff = 1
        // K=2, 余り1（奇数） → No
        assert!(!solve(&[1], &[2], 2));
    }

    #[test]
    fn example3() {
        // A=[1], B=[2]
        // diff = 1
        // K=3, 余り2（偶数） → Yes
        assert!(solve(&[1], &[2], 3));
    }

    #[test]
    fn not_enough() {
        // diff > K
        // 操作回数が足りない
        assert!(!solve(&[1], &[10], 5));
    }

    #[test]
    fn already_equal() {
        // A = B
        // diff = 0
        // K=0 → Yes, K=1 → No, K=2 → Yes
        assert!(solve(&[1, 2, 3], &[1, 2, 3], 0));
        assert!(!solve(&[1, 2, 3], &[1, 2, 3], 1));
        assert!(solve(&[1, 2, 3], &[1, 2, 3], 2));
    }

    #[test]
    fn large_k() {
        // diff = 3, K = 1000001
        // 余り = 999998（偶数） → Yes
        assert!(solve(&[1, 2, 3], &[2, 3, 4], 1000001));
    }
}
