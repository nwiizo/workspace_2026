// 002 - Encyclopedia of Parentheses (★3)
// https://atcoder.jp/contests/typical90/tasks/typical90_b
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたは「カッコの百科事典」を作ることになりました。
// 長さ N の「正しいカッコ列」を、辞書順にすべて載せたいのです。
//
// 「正しいカッコ列」とは何でしょう？
//
// 【正しい例】
// - "()"       ← 開いて閉じる。OK！
// - "(())"     ← 入れ子も OK！
// - "()()"     ← 並べても OK！
// - "((()))"   ← 深い入れ子も OK！
//
// 【ダメな例】
// - ")("       ← 閉じるカッコが先に来ちゃダメ！
// - "(()"      ← 閉じ忘れ！
// - "())"      ← 閉じすぎ！
// - "((("      ← 全部開いてるだけ！
//
// ============================================================================
// 【正しいカッコ列の条件 - 銀行口座のたとえ】
// ============================================================================
//
// カッコ列を「銀行口座」で考えてみましょう。
// - '(' = 1万円を預ける
// - ')' = 1万円を引き出す
//
// 正しいカッコ列の条件：
// 1. 最後に残高が 0 円になること（預けた分だけ引き出す）
// 2. 途中で残高がマイナスにならないこと（持っていない分は引き出せない）
//
// 例: "(())"
// - '(' → 残高 1万円
// - '(' → 残高 2万円
// - ')' → 残高 1万円
// - ')' → 残高 0万円 ✓
//
// 例: "))(("
// - ')' → 残高 -1万円 ✗（マイナスになった！）
//
// ============================================================================
// 【解法：bit全探索】
// ============================================================================
//
// N が最大 20 と小さいので、「全部試す」ことができます！
//
// 各位置で '(' か ')' のどちらかを選ぶので、
// 全部で 2^N 通りの組み合わせがあります。
//
// 2^20 = 1,048,576 ≈ 100万通り
//
// 100万回のチェックは、コンピュータなら一瞬です。
// （1秒間に1億回くらいの処理ができるので）
//
// ============================================================================
// 【bit全探索とは？ - スイッチのたとえ】
// ============================================================================
//
// N 個のスイッチがあって、それぞれ ON/OFF を選べると考えましょう。
// - スイッチ1: ON/OFF
// - スイッチ2: ON/OFF
// - ...
// - スイッチN: ON/OFF
//
// 全パターンは 2^N 通り。
//
// コンピュータでは「整数のビット」でこれを表現します。
// 例えば N=4 のとき、整数 0〜15 の各ビットがスイッチに対応：
//
//   0 = 0000 → 全部 OFF
//   1 = 0001 → スイッチ1だけ ON
//   2 = 0010 → スイッチ2だけ ON
//   3 = 0011 → スイッチ1,2 が ON
//   ...
//  15 = 1111 → 全部 ON
//
// 今回は：
// - ビットが 0 → '(' を選ぶ
// - ビットが 1 → ')' を選ぶ
//
// すると、整数を 0 から順に増やすと、
// 自然と辞書順（'(' が ')' より先）になります！
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - 全パターン: O(2^N)
// - 各パターンの検証: O(N)
// - 合計: O(N × 2^N)
//
// N=20 のとき、約 2000万回の操作。十分高速です。
//
// ============================================================================

use proconio::input;

fn main() {
    input! {
        n: usize,   // カッコ列の長さ
    }
    solve(n);
}

fn solve(n: usize) {
    // -------------------------------------------------------------------------
    // 【奇数チェック】
    //
    // 正しいカッコ列は '(' と ')' が同数なので、長さは必ず偶数。
    // 奇数なら正しいカッコ列は1つも存在しません。
    // -------------------------------------------------------------------------
    if n % 2 == 1 {
        return;
    }

    // -------------------------------------------------------------------------
    // 【bit全探索】
    //
    // 0 から 2^N - 1 まで、すべての整数を試します。
    //
    // 1u64 << n は「1を左にnビットシフト」= 2^N を計算する方法。
    // 例: 1u64 << 4 = 0b10000 = 16 = 2^4
    //
    // u64 は「64ビットの符号なし整数」。大きな数を扱うために使います。
    // -------------------------------------------------------------------------
    for mask in 0..(1u64 << n) {
        if is_valid_parentheses(mask, n) {
            // ビット列を文字列に変換
            let s: String = (0..n)
                .map(|i| {
                    // i番目のビットを取り出す
                    // mask >> i: maskを右にiビットシフト
                    // & 1: 一番右のビットだけ取り出す（0 or 1）
                    if (mask >> i) & 1 == 0 {
                        '(' // ビットが0なら開きカッコ
                    } else {
                        ')' // ビットが1なら閉じカッコ
                    }
                })
                .collect();
            println!("{}", s);
        }
    }
}

/// このビット列が「正しいカッコ列」を表しているか判定
///
/// # 判定方法（銀行口座方式）
///
/// 左から順番に見ていって：
/// - '(' なら残高 +1
/// - ')' なら残高 -1
///
/// 途中でマイナスになったら NG、最後に 0 でなければ NG
fn is_valid_parentheses(mask: u64, n: usize) -> bool {
    let mut open_count = 0i32; // '(' の累計（預金回数）
    let mut close_count = 0i32; // ')' の累計（引き出し回数）

    for i in 0..n {
        if (mask >> i) & 1 == 0 {
            open_count += 1; // '(' を見つけた
        } else {
            close_count += 1; // ')' を見つけた
        }

        // -------------------------------------------------------------------------
        // 【途中チェック】
        //
        // どの時点でも ')' が '(' を超えてはいけない。
        // 「まだ開いていないカッコを閉じる」ことはできないから。
        //
        // これは「残高がマイナスになってはいけない」と同じ。
        // -------------------------------------------------------------------------
        if close_count > open_count {
            return false;
        }
    }

    // -------------------------------------------------------------------------
    // 【最終チェック】
    //
    // 最後に '(' と ')' の数が同じでなければならない。
    // 開いたカッコは全部閉じる必要がある。
    // -------------------------------------------------------------------------
    open_count == close_count
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_n2() {
        // N=2 のとき、正しいカッコ列は "()" の1つだけ
        //
        // 【ビット表現の見方】
        // 0b10 = 二進数で 10 = 十進数で 2
        // 右から読んで: 位置0=0, 位置1=1 → "()"
        //
        // 【4パターンの検証】
        assert!(is_valid_parentheses(0b10, 2)); // "()" ← これだけOK
        assert!(!is_valid_parentheses(0b00, 2)); // "((" ← 閉じてない
        assert!(!is_valid_parentheses(0b01, 2)); // ")(" ← 最初から閉じてる
        assert!(!is_valid_parentheses(0b11, 2)); // "))" ← 最初から閉じてる
    }

    #[test]
    fn test_n4() {
        // N=4 のとき、正しいカッコ列は "(())" と "()()" の2つ
        //
        // "(())" → 位置 0,1,2,3 = '(','(',')',')' → ビット 0,0,1,1 → 0b1100
        // "()()" → 位置 0,1,2,3 = '(',')',')','(' → ビット 0,1,0,1 → 0b1010
        //
        // ※ ビットは右から左に並ぶので、見た目が逆になることに注意
        assert!(is_valid_parentheses(0b1100, 4)); // "(())"
        assert!(is_valid_parentheses(0b1010, 4)); // "()()"
    }

    #[test]
    fn test_n6() {
        // N=6 のとき、正しいカッコ列は 5 つ
        // "((()))", "(()())", "(())()", "()(())", "()()()"
        //
        // カタラン数という数列で、n番目の値が答えの数になります。
        // C_1=1, C_2=2, C_3=5, C_4=14, ...
        let mut count = 0;
        for mask in 0..(1u64 << 6) {
            if is_valid_parentheses(mask, 6) {
                count += 1;
            }
        }
        assert_eq!(count, 5);
    }
}
