// 018 - Statue of Chokudai (★3)
// https://atcoder.jp/contests/typical90/tasks/typical90_r
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// 遊園地に観覧車があります。
// ある1つのゴンドラに「ちょくだい像」が乗っています。
//
// 観覧車の仕様:
// - 一周するのに T 秒かかる
// - 半径は 1 メートル
// - 中心の高さは X メートル
// - 観測点から観覧車の軸までの水平距離は L メートル
// - 時刻 0 のとき、ちょくだい像は最下点にいる
//
//            中心 (高さ X)
//              ●
//            / | \
//           /  |  \    半径 1
//          ●   |   ●
//             \|/
//              ●  ← 時刻 0 でここ（最下点）
//
//   観測点 ●-----------------● 軸
//         ←--------- L -------→
//
// Q 個のクエリで、各時刻にちょくだい像を見上げる角度（仰角）を求めます。
//
// ============================================================================
// 【解法：三角関数】
// ============================================================================
//
// 【時刻 t での位置】
//
// 回転角 θ = 2π × (t / T) - π/2
// （-π/2 は最下点からスタートするため）
//
// ちょくだい像の高さ:
// y = X + sin(θ) × 1 = X + sin(θ)
//
// 【仰角の計算】
//
// 仰角 = arctan(高さ / 水平距離) = arctan(y / L)
//
// ラジアンから度数法に変換して出力。
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - 各クエリ: O(1)
// - Q 回のクエリ: O(Q)
//
// ============================================================================

use proconio::input;
use std::f64::consts::PI;

fn main() {
    input! {
        t: f64,     // 1周にかかる時間（秒）
        l: f64,     // 観測点から回転軸までの水平距離（メートル）
        x: f64,     // 回転の中心の高さ（メートル）
        q: usize,   // クエリ数
    }

    for _ in 0..q {
        input! { e: f64 }   // 経過時間（秒）
        let angle = calc_elevation(t, l, x, e);
        println!("{}", angle);
    }
}

/// 仰角を計算（度数法）
fn calc_elevation(period: f64, dist: f64, center_height: f64, time: f64) -> f64 {
    // -------------------------------------------------------------------------
    // 【回転角の計算】
    //
    // 時刻 0 で最下点（-π/2 ラジアン）
    // 時刻 T で一周して再び最下点
    //
    // θ = 2π × (t / T) - π/2
    // -------------------------------------------------------------------------
    let theta = 2.0 * PI * time / period - PI / 2.0;

    // -------------------------------------------------------------------------
    // 【高さの計算】
    //
    // y = 中心の高さ + 半径 × sin(θ)
    // 半径は 1 メートル
    // -------------------------------------------------------------------------
    let y = center_height + theta.sin();

    // -------------------------------------------------------------------------
    // 【仰角の計算】
    //
    // 仰角 = arctan(高さ / 水平距離)
    // atan を使用（atan2 より簡単、この場合は dist > 0 なので問題なし）
    //
    // ラジアン → 度数法に変換
    // -------------------------------------------------------------------------
    let elevation_rad = (y / dist).atan();
    elevation_rad * 180.0 / PI
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    fn approx_eq(a: f64, b: f64) -> bool {
        (a - b).abs() < 1e-6
    }

    #[test]
    fn test_at_bottom() {
        // t=0 で最下点
        // y = X - 1（最下点は中心から半径分下）
        // 仰角 = atan((X-1)/L)
        let angle = calc_elevation(4.0, 10.0, 5.0, 0.0);
        let expected = ((5.0 - 1.0) / 10.0_f64).atan() * 180.0 / PI;
        assert!(approx_eq(angle, expected));
    }

    #[test]
    fn test_at_top() {
        // t=T/2 で最上点
        // θ = 2π × (T/2)/T - π/2 = π - π/2 = π/2
        // sin(π/2) = 1
        // y = X + 1
        let angle = calc_elevation(4.0, 10.0, 5.0, 2.0);
        let expected = ((5.0 + 1.0) / 10.0_f64).atan() * 180.0 / PI;
        assert!(approx_eq(angle, expected));
    }

    #[test]
    fn test_at_quarter() {
        // t=T/4 で横向き（右側）
        // θ = 2π × (1/4) - π/2 = π/2 - π/2 = 0
        // sin(0) = 0
        // y = X
        let angle = calc_elevation(4.0, 10.0, 5.0, 1.0);
        let expected = (5.0 / 10.0_f64).atan() * 180.0 / PI;
        assert!(approx_eq(angle, expected));
    }

    #[test]
    fn test_full_rotation() {
        // t=T で一周して最下点に戻る
        // 結果は t=0 と同じ
        let angle1 = calc_elevation(4.0, 10.0, 5.0, 0.0);
        let angle2 = calc_elevation(4.0, 10.0, 5.0, 4.0);
        assert!(approx_eq(angle1, angle2));
    }
}
