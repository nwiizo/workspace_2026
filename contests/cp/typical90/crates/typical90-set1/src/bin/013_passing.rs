// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_dijkstra() {
        // 単純なパスグラフ: 0 --1-- 1 --1-- 2
        let graph = vec![vec![(1, 1)], vec![(0, 1), (2, 1)], vec![(1, 1)]];

        let dist = dijkstra(&graph, 0);
        assert_eq!(dist, vec![0, 1, 2]);
    }

    #[test]
    fn test_passing() {
        // 0 --1-- 1 --1-- 2
        //
        // dist1 = [0, 1, 2]  (0からの距離)
        // distN = [2, 1, 0]  (2からの距離)
        //
        // 各頂点を経由する場合:
        // 頂点0: 0 + 2 = 2
        // 頂点1: 1 + 1 = 2
        // 頂点2: 2 + 0 = 2
        let graph = vec![vec![(1, 1)], vec![(0, 1), (2, 1)], vec![(1, 1)]];

        let dist1 = dijkstra(&graph, 0);
        let dist_n = dijkstra(&graph, 2);

        assert_eq!(dist1[0] + dist_n[0], 2);
        assert_eq!(dist1[1] + dist_n[1], 2);
        assert_eq!(dist1[2] + dist_n[2], 2);
    }

    #[test]
    fn test_triangle() {
        // 三角形グラフ
        //     0
        //    / \
        //   1   3
        //  /     \
        // 1 --2-- 2
        //
        // 0-1: コスト1, 0-2: コスト3, 1-2: コスト2
        let graph = vec![
            vec![(1, 1), (2, 3)],
            vec![(0, 1), (2, 2)],
            vec![(0, 3), (1, 2)],
        ];

        let dist = dijkstra(&graph, 0);
        assert_eq!(dist[0], 0);
        assert_eq!(dist[1], 1);
        assert_eq!(dist[2], 3); // 0→1→2 = 1+2 = 3 < 0→2 = 3
    }
}
