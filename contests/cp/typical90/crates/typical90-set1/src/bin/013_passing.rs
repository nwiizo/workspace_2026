// 013 - Passing (★5)
// https://atcoder.jp/contests/typical90/tasks/typical90_m
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたは旅行プランナーです。
// N 個の都市があり、M 本の道路でつながっています。
// 各道路には移動時間（コスト）があります。
//
// クライアントは「都市1から都市Nへ、必ず都市Kを経由して行きたい」と言っています。
// 各都市 K (1, 2, ..., N) を経由するとき、最短の所要時間を教えてください。
//
// 例:
//   1 --3-- 2 --2-- 3
//
// - 都市1を経由: 1→3 = 3+2 = 5
// - 都市2を経由: 1→2→3 = 3+2 = 5
// - 都市3を経由: 1→3 = 5
//
// 答え: 5, 5, 5
//
// ============================================================================
// 【解法：両端からダイクストラ】
// ============================================================================
//
// 【素朴なアイデア】
// 各 K について「1→K→N」の最短経路を求める？
// → K が N 個あるので、N 回ダイクストラ → O(N × M log N) で遅い！
//
// 【賢いアイデア】
// 「1→K」と「K→N」を分けて考える。
//
// dist1[K] = 都市1から都市Kへの最短距離
// distN[K] = 都市Nから都市Kへの最短距離（= K→N と同じ、無向グラフなので）
//
// 答え = dist1[K] + distN[K]
//
// dist1 は都市1からのダイクストラ1回で全て求まる。
// distN は都市Nからのダイクストラ1回で全て求まる。
// → たった2回のダイクストラで完了！
//
// ============================================================================
// 【ダイクストラ法とは？】
// ============================================================================
//
// 重み付きグラフで、始点から全頂点への最短距離を求めるアルゴリズム。
//
// 【アイデア】
// 「確定済み」の頂点から、距離が小さい順に探索を広げていく。
//
// 【手順】
// 1. 始点の距離を0、他を∞に初期化
// 2. 優先度付きキュー（最小ヒープ）に始点を追加
// 3. キューから最小距離の頂点を取り出す
// 4. その頂点から行ける頂点の距離を更新（もっと短い経路があれば）
// 5. 更新した頂点をキューに追加
// 6. キューが空になるまで繰り返す
//
// 【なぜ正しい？】
// 最小距離の頂点を取り出した時点で、その距離は確定している。
// なぜなら、まだ見ていない頂点経由で更に短くなることはないから。
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - ダイクストラ1回: O(M log N)
// - 2回実行: O(2 × M log N) = O(M log N)
//
// ============================================================================

use proconio::input;
use proconio::marker::Usize1;
use std::cmp::Reverse;
use std::collections::BinaryHeap;

fn main() {
    input! {
        n: usize,
        m: usize,
        edges: [(Usize1, Usize1, i64); m], // (始点, 終点, コスト)
    }

    // -------------------------------------------------------------------------
    // 【隣接リスト構築】
    //
    // graph[v] = [(隣接頂点, 辺のコスト), ...]
    // 無向グラフなので、両方向に辺を追加
    // -------------------------------------------------------------------------
    let mut graph = vec![vec![]; n];
    for &(a, b, c) in &edges {
        graph[a].push((b, c));
        graph[b].push((a, c));
    }

    // -------------------------------------------------------------------------
    // 【両端からダイクストラ】
    // -------------------------------------------------------------------------
    let dist1 = dijkstra(&graph, 0);       // 都市1(index 0)から
    let dist_n = dijkstra(&graph, n - 1);  // 都市N(index n-1)から

    // -------------------------------------------------------------------------
    // 【各頂点を経由する最短距離を出力】
    // -------------------------------------------------------------------------
    for k in 0..n {
        println!("{}", dist1[k] + dist_n[k]);
    }
}

/// ダイクストラ法で始点から全頂点への最短距離を求める
///
/// # 引数
/// - graph: 隣接リスト形式のグラフ
/// - start: 始点のインデックス
///
/// # 戻り値
/// - dist[v] = start から v への最短距離
fn dijkstra(graph: &[Vec<(usize, i64)>], start: usize) -> Vec<i64> {
    let n = graph.len();

    // -------------------------------------------------------------------------
    // 【距離配列の初期化】
    //
    // i64::MAX = ∞ として扱う
    // -------------------------------------------------------------------------
    let mut dist = vec![i64::MAX; n];
    dist[start] = 0;

    // -------------------------------------------------------------------------
    // 【優先度付きキュー（最小ヒープ）】
    //
    // Rust の BinaryHeap は最大ヒープなので、Reverse で包んで最小ヒープにする
    // (距離, 頂点) のタプルを格納
    // -------------------------------------------------------------------------
    let mut heap = BinaryHeap::new();
    heap.push(Reverse((0i64, start)));

    // -------------------------------------------------------------------------
    // 【メインループ】
    // -------------------------------------------------------------------------
    while let Some(Reverse((d, v))) = heap.pop() {
        // 既により短い距離が確定している場合はスキップ
        if d > dist[v] {
            continue;
        }

        // v から行ける全ての頂点を確認
        for &(next, cost) in &graph[v] {
            let new_dist = d + cost;

            // より短い経路が見つかった場合
            if new_dist < dist[next] {
                dist[next] = new_dist;
                heap.push(Reverse((new_dist, next)));
            }
        }
    }

    dist
}

