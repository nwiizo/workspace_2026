#[cfg(test)]
mod tests {
    use super::*;

    fn to_grid(s: &[&str]) -> Vec<Vec<char>> {
        s.iter().map(|row| row.chars().collect()).collect()
    }

    #[test]
    fn example1() {
        // 2x2 全て空
        //
        // . .    キングの配置可能パターン:
        // . .    - 0個: 1通り
        //        - 1個: 4通り（各マス）
        //        - 2個以上: 全て隣接するため不可
        //
        // 答え: 5通り
        let grid = to_grid(&["..", ".."]);
        assert_eq!(solve(2, 2, &grid), 5);
    }

    #[test]
    fn example2() {
        // 障害物あり
        //
        // . #    右上が障害物
        // . .
        //
        // - 0個: 1通り
        // - 1個: (0,0), (1,0), (1,1) の3通り
        // - 2個以上: 全て隣接するため不可
        //
        // 答え: 4通り
        let grid = to_grid(&[".#", ".."]);
        assert_eq!(solve(2, 2, &grid), 4);
    }

    #[test]
    fn all_blocked() {
        // 全て障害物 → キングは0個のみ
        let grid = to_grid(&["##", "##"]);
        assert_eq!(solve(2, 2, &grid), 1);
    }

    #[test]
    fn single_cell() {
        // 1×1
        // 0個または1個 → 2通り
        let grid = to_grid(&["."]);
        assert_eq!(solve(1, 1, &grid), 2);
    }

    #[test]
    fn row_1x3() {
        // 1×3: 横一列
        //
        // . . .
        //
        // 有効な配置（横に隣接しない）:
        // - 000: 1通り
        // - 100, 010, 001: 3通り
        // - 101: 1通り
        //
        // 答え: 5通り（フィボナッチ数列!）
        let grid = to_grid(&["..."]);
        assert_eq!(solve(1, 3, &grid), 5);
    }

    #[test]
    fn column_3x1() {
        // 3×1: 縦一列
        //
        // .
        // .
        // .
        //
        // 同様に、縦に隣接しない配置:
        // - 000: 1通り
        // - 100, 010, 001: 3通り
        // - 101: 1通り
        //
        // 答え: 5通り
        let grid = to_grid(&[".", ".", "."]);
        assert_eq!(solve(3, 1, &grid), 5);
    }
}
