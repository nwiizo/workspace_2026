// 023 - Avoid War (★7)
// https://atcoder.jp/contests/typical90/tasks/typical90_w
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// チェス盤に「キング」を配置するゲームです。
//
// キングは8方向（上下左右＋斜め4方向）に動けるコマ。
// キング同士が隣接すると「戦争」が起きてしまうので、
// 隣り合わないように配置したい。
//
// さらに、盤面には「障害物」(#) があり、そこにはキングを置けません。
//
// キングの配置方法は何通りあるでしょうか？（0個配置も含む）
//
// 例: 2×2 のグリッド（全て空きマス）
//
//   . .
//   . .
//
// - 0個配置: 1通り
// - 1個配置: 4通り（各マスに1個ずつ）
// - 2個以上: 全てのマスが隣接しているので不可能
//
// 答え: 5通り
//
// ============================================================================
// 【解法：ビットマスクDP】
// ============================================================================
//
// 【なぜビットマスク？】
//
// 1行のキングの配置を「ビット列」で表す。
// W 列なら、2^W 通りの配置がある。
//
// 例: W=3
// - 000: キングなし
// - 001: 右端にキング
// - 010: 中央にキング
// - 101: 両端にキング（中央は空き）
//
// 【状態設計】
//
// dp[mask] = 「現在の行の配置が mask」のときの場合の数
//
// 【遷移条件】
//
// 前の行の mask (prev_mask) から今の行の mask (curr_mask) に遷移できる条件:
//
// 1. curr_mask 自体が有効（横に隣接するビットがない）
//    → (curr_mask & (curr_mask >> 1)) == 0
//
// 2. 障害物のあるマスにキングがない
//    → (curr_mask & obstacle[row]) == 0
//
// 3. prev_mask と curr_mask が縦・斜めに隣接しない
//    → (prev_mask & curr_mask) == 0           // 縦方向
//    → ((prev_mask << 1) & curr_mask) == 0    // 右斜め
//    → ((prev_mask >> 1) & curr_mask) == 0    // 左斜め
//
// 【有効な行マスクの前計算】
//
// 「横に隣接するビットがない」マスクを前計算しておく。
// これで無駄な遷移を減らせる。
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - 有効な行マスク: フィボナッチ数程度（約 O(φ^W), φ≒1.618）
// - 遷移: O(valid_masks^2)
// - 行数: H 回
// - W ≤ 14 なら間に合う
//
// ============================================================================

use proconio::input;
use proconio::marker::Chars;

const MOD: i64 = 1_000_000_007;

fn main() {
    input! {
        h: usize,
        w: usize,
        grid: [Chars; h],
    }
    println!("{}", solve(h, w, &grid));
}

fn solve(h: usize, w: usize, grid: &[Vec<char>]) -> i64 {
    // -------------------------------------------------------------------------
    // 【障害物マスクの構築】
    //
    // obstacle[i] の j ビット目が 1 なら、(i, j) は障害物
    // -------------------------------------------------------------------------
    let obstacle: Vec<u32> = grid
        .iter()
        .map(|row| {
            row.iter()
                .enumerate()
                .filter(|&(_, &c)| c == '#')
                .fold(0u32, |acc, (j, _)| acc | (1 << j))
        })
        .collect();

    // -------------------------------------------------------------------------
    // 【有効な行マスクの前計算】
    //
    // 「横に隣接するビットがない」マスクを列挙
    // 条件: (mask & (mask >> 1)) == 0
    // -------------------------------------------------------------------------
    let valid_row_masks: Vec<u32> = (0..(1 << w))
        .filter(|&mask| (mask & (mask >> 1)) == 0)
        .collect();

    // -------------------------------------------------------------------------
    // 【DPの初期化】
    //
    // dp[mask] = 現在の行で mask を選んだときの場合の数
    // 初期状態: dp[0] = 1（0行目の前、何も配置していない）
    // -------------------------------------------------------------------------
    let mut dp = vec![0i64; 1 << w];
    dp[0] = 1;

    // -------------------------------------------------------------------------
    // 【行ごとのDP遷移】
    //
    // 各行について、全ての有効な (prev_mask, curr_mask) ペアを試す
    // -------------------------------------------------------------------------
    for &obs in obstacle.iter().take(h) {
        let mut new_dp = vec![0i64; 1 << w];

        for &curr_mask in &valid_row_masks {
            // 障害物チェック: 障害物のあるマスにキングがあるならスキップ
            if (curr_mask & obs) != 0 {
                continue;
            }

            for &prev_mask in &valid_row_masks {
                if dp[prev_mask as usize] == 0 {
                    continue;
                }

                // -------------------------------------------------------------
                // 【縦・斜め隣接チェック】
                //
                // 前の行と今の行のキングが縦・斜めに隣接していないか確認
                // -------------------------------------------------------------

                // 縦方向: 同じ列にキングがある
                if (prev_mask & curr_mask) != 0 {
                    continue;
                }

                // 右斜め: prev の左隣と curr が重なる
                if ((prev_mask << 1) & curr_mask) != 0 {
                    continue;
                }

                // 左斜め: prev の右隣と curr が重なる
                if ((prev_mask >> 1) & curr_mask) != 0 {
                    continue;
                }

                new_dp[curr_mask as usize] =
                    (new_dp[curr_mask as usize] + dp[prev_mask as usize]) % MOD;
            }
        }

        dp = new_dp;
    }

    // -------------------------------------------------------------------------
    // 【答え: 全マスクの合計】
    //
    // 最終行のどの配置で終わっても良いので、全て足し合わせる
    // -------------------------------------------------------------------------
    dp.iter().fold(0, |acc, &x| (acc + x) % MOD)
}

