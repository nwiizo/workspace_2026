// 014 - We Used to Sing a Song Together (★3)
// https://atcoder.jp/contests/typical90/tasks/typical90_n
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたは小学校の先生です。
// N 人の子供がいて、それぞれの家の位置 A_i が決まっています。
// N 軒の家があり、それぞれの位置 B_j が決まっています。
//
// 各子供を1つの家に割り当てます（1対1対応）。
// 子供が家まで歩く距離の合計を最小化してください。
//
// 例:
//   子供の位置: [2, 3, 4]
//   家の位置: [1, 2, 6]
//
// 割り当て1: 2→1, 3→2, 4→6 → |2-1| + |3-2| + |4-6| = 1 + 1 + 2 = 4 ✓
// 割り当て2: 2→2, 3→6, 4→1 → |0| + |3| + |3| = 6 ✗
//
// 最小は 4
//
// ============================================================================
// 【解法：ソートして対応させる】
// ============================================================================
//
// 【直感的な理解】
//
// ソートすると、「近い者同士」を対応させることになる。
// 交差する対応（例: 左の子供が右の家、右の子供が左の家）は
// 必ず総距離が増える。
//
// 【なぜソートで最適？】
//
// 仮に、ソート後に「交差」があったとする:
//   子供 a < b、家 x < y で、a→y, b→x と対応
//
// この場合:
//   距離 = |a-y| + |b-x|
//
// 「非交差」に変えると:
//   a→x, b→y
//   距離 = |a-x| + |b-y|
//
// a < b, x < y のとき、非交差の方が必ず距離が短い（または同じ）。
//
// 【証明のスケッチ】
// 交差: (y-a) + (b-x) = y - a + b - x
// 非交差: (x-a) + (y-b)  または (a-x) + (b-y) など場合分け
// → 非交差の方が常に小さい（三角不等式）
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - ソート: O(N log N)
// - 距離計算: O(N)
// - 合計: O(N log N)
//
// ============================================================================

use proconio::input;

fn main() {
    input! {
        n: usize,
        a: [i64; n],    // 子供の位置
        b: [i64; n],    // 家の位置
    }
    println!("{}", solve(&a, &b));
}

fn solve(a: &[i64], b: &[i64]) -> i64 {
    // -------------------------------------------------------------------------
    // 【ソート】
    //
    // sort_unstable は安定ソートではないが、高速。
    // 数値のソートでは問題なし。
    // -------------------------------------------------------------------------
    let mut a = a.to_vec();
    let mut b = b.to_vec();
    a.sort_unstable();
    b.sort_unstable();

    // -------------------------------------------------------------------------
    // 【距離の合計を計算】
    //
    // zip: 2つのイテレータを同時に進める
    // (a[0], b[0]), (a[1], b[1]), ... のペアが得られる
    //
    // map: 各ペアの距離を計算
    // sum: 合計
    // -------------------------------------------------------------------------
    a.iter().zip(b.iter()).map(|(x, y)| (x - y).abs()).sum()
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn example1() {
        // 子供: [2, 3, 4] → ソート済み
        // 家: [1, 2, 6] → ソート済み
        //
        // 対応: 2→1, 3→2, 4→6
        // 距離: |2-1| + |3-2| + |4-6| = 1 + 1 + 2 = 4
        assert_eq!(solve(&[2, 3, 4], &[1, 2, 6]), 4);
    }

    #[test]
    fn example2() {
        // 子供: [1, 5]
        // 家: [3, 4]
        //
        // ソート後も同じ
        // 対応: 1→3, 5→4
        // 距離: |1-3| + |5-4| = 2 + 1 = 3
        assert_eq!(solve(&[1, 5], &[3, 4]), 3);
    }

    #[test]
    fn same_positions() {
        // 全員同じ位置 → 距離0
        assert_eq!(solve(&[1, 2, 3], &[1, 2, 3]), 0);
    }

    #[test]
    fn reversed() {
        // 子供: [3, 2, 1]
        // 家: [1, 2, 3]
        //
        // ソート後: 両方 [1, 2, 3]
        // 対応: 1→1, 2→2, 3→3
        // 距離: 0
        assert_eq!(solve(&[3, 2, 1], &[1, 2, 3]), 0);
    }

    #[test]
    fn negative_positions() {
        // 負の座標も対応可能
        assert_eq!(solve(&[-5, 0, 5], &[-4, 1, 6]), 3);
    }
}
