// 012 - Red Painting (★4)
// https://atcoder.jp/contests/typical90/tasks/typical90_l
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// あなたは塗り絵アプリの開発者です。
// H × W のグリッド（最初は全て白）があります。
//
// Q 個のクエリが来ます:
//
// クエリ1: マス (r, c) を赤く塗る
// クエリ2: マス (ra, ca) と (rb, cb) が「赤で繋がっているか」判定
//
// 「繋がっている」とは:
// - 両方とも赤色である
// - 隣接する赤マスだけを通って移動できる（上下左右）
//
// 例:
//   ■ □ ■     ■ = 赤, □ = 白
//   ■ ■ □
//   □ ■ □
//
// (0,0) と (2,1) は繋がっている: (0,0)→(1,0)→(1,1)→(2,1)
// (0,0) と (0,2) は繋がっていない: 間に白マスがある
//
// ============================================================================
// 【解法：Union-Find（素集合データ構造）】
// ============================================================================
//
// 【Union-Find とは？】
//
// グループ（集合）を管理するデータ構造。
// 「同じグループに属するか？」「2つのグループを合併する」が高速にできる。
//
// 主な操作:
// - find(x): x が属するグループの代表を返す
// - unite(x, y): x と y のグループを合併する
// - same(x, y): x と y が同じグループか判定する
//
// 【計算量】
//
// 経路圧縮 + ランク付き合併を使うと:
// - find, unite, same: ほぼ O(1)（正確には O(α(N))、α は逆アッカーマン関数）
//
// ============================================================================
// 【この問題での使い方】
// ============================================================================
//
// 各マスを要素として Union-Find を作る。
// マス (r, c) は r * W + c という1次元インデックスで管理。
//
// クエリ1（赤く塗る）:
// 1. マスを「赤」にマーク
// 2. 隣接する4方向を見て、既に赤いマスがあれば unite
//
// クエリ2（連結判定）:
// 1. 両方とも赤でなければ No
// 2. 両方赤なら same で判定
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - 各クエリ: O(α(HW)) ≈ O(1)
// - Q 回のクエリ: O(Q)
// - 合計: O(HW + Q)
//
// ============================================================================

use proconio::input;

fn main() {
    input! {
        h: usize,
        w: usize,
        q: usize,
    }

    // -------------------------------------------------------------------------
    // 【初期化】
    //
    // Union-Find: 各マスが独立したグループ
    // is_red: 各マスが赤かどうか（最初は全て false）
    // -------------------------------------------------------------------------
    let mut uf = UnionFind::new(h * w);
    let mut is_red = vec![vec![false; w]; h];

    for _ in 0..q {
        input! { query_type: usize }

        match query_type {
            1 => {
                // -----------------------------------------------------------------
                // 【クエリ1: マスを赤く塗る】
                // -----------------------------------------------------------------
                input! { r: usize, c: usize }
                let (r, c) = (r - 1, c - 1); // 1-indexed → 0-indexed

                is_red[r][c] = true;

                // 隣接する4方向を確認
                let dirs = [(0, 1), (1, 0), (0, -1), (-1, 0)];
                for (dr, dc) in dirs {
                    let nr = r as i32 + dr;
                    let nc = c as i32 + dc;

                    // 範囲内かチェック
                    if nr >= 0 && nr < h as i32 && nc >= 0 && nc < w as i32 {
                        let (nr, nc) = (nr as usize, nc as usize);

                        // 隣が赤なら連結
                        if is_red[nr][nc] {
                            uf.unite(r * w + c, nr * w + nc);
                        }
                    }
                }
            }
            2 => {
                // -----------------------------------------------------------------
                // 【クエリ2: 連結判定】
                // -----------------------------------------------------------------
                input! { ra: usize, ca: usize, rb: usize, cb: usize }
                let (ra, ca, rb, cb) = (ra - 1, ca - 1, rb - 1, cb - 1);

                // 両方赤で、かつ同じグループなら Yes
                if is_red[ra][ca] && is_red[rb][cb] && uf.same(ra * w + ca, rb * w + cb) {
                    println!("Yes");
                } else {
                    println!("No");
                }
            }
            _ => unreachable!(),
        }
    }
}

// =============================================================================
// 【Union-Find データ構造】
// =============================================================================
struct UnionFind {
    parent: Vec<usize>, // 各要素の親
    rank: Vec<usize>,   // 各根のランク（木の高さの目安）
}

impl UnionFind {
    /// n 要素の Union-Find を作成（最初は全員バラバラ）
    fn new(n: usize) -> Self {
        Self {
            parent: (0..n).collect(), // 最初は自分自身が親
            rank: vec![0; n],
        }
    }

    /// x が属するグループの代表（根）を返す
    ///
    /// 経路圧縮: 見つかった根を直接親にすることで、次回以降を高速化
    fn find(&mut self, x: usize) -> usize {
        if self.parent[x] != x {
            self.parent[x] = self.find(self.parent[x]); // 経路圧縮
        }
        self.parent[x]
    }

    /// x と y のグループを合併
    ///
    /// ランク付き合併: 木の高さを抑えるため、低い方を高い方に繋げる
    fn unite(&mut self, x: usize, y: usize) {
        let (rx, ry) = (self.find(x), self.find(y));
        if rx == ry {
            return; // 既に同じグループ
        }

        // ランクが低い方を高い方に繋げる
        if self.rank[rx] < self.rank[ry] {
            self.parent[rx] = ry;
        } else {
            self.parent[ry] = rx;
            if self.rank[rx] == self.rank[ry] {
                self.rank[rx] += 1;
            }
        }
    }

    /// x と y が同じグループに属するか判定
    fn same(&mut self, x: usize, y: usize) -> bool {
        self.find(x) == self.find(y)
    }
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_union_find_basic() {
        let mut uf = UnionFind::new(5);

        // 最初は全員別グループ
        assert!(!uf.same(0, 1));
        assert!(!uf.same(1, 2));

        // 0 と 1 を合併
        uf.unite(0, 1);
        assert!(uf.same(0, 1));
        assert!(!uf.same(0, 2));

        // 1 と 2 を合併 → 0, 1, 2 が同じグループに
        uf.unite(1, 2);
        assert!(uf.same(0, 2));
    }

    #[test]
    fn test_grid_example() {
        // 3×3 グリッド
        // マスの番号: 0  1  2
        //             3  4  5
        //             6  7  8
        let mut uf = UnionFind::new(9);

        // (0,0), (1,0), (1,1), (2,1) を赤く塗って連結
        // インデックス: 0, 3, 4, 7
        uf.unite(0, 3); // (0,0) - (1,0)
        uf.unite(3, 4); // (1,0) - (1,1)
        uf.unite(4, 7); // (1,1) - (2,1)

        assert!(uf.same(0, 7)); // (0,0) と (2,1) は連結
        assert!(!uf.same(0, 2)); // (0,0) と (0,2) は非連結
    }

    #[test]
    fn test_path_compression() {
        let mut uf = UnionFind::new(10);

        // 長い連鎖を作る
        for i in 0..9 {
            uf.unite(i, i + 1);
        }

        // 全て同じグループ
        assert!(uf.same(0, 9));

        // 経路圧縮により、find は高速
        let root = uf.find(0);
        for i in 0..10 {
            assert_eq!(uf.find(i), root);
        }
    }
}
