// 022 - Cubic Cake (★2)
// https://atcoder.jp/contests/typical90/tasks/typical90_v
//
// ============================================================================
// 【物語で理解する問題】
// ============================================================================
//
// パティシエがケーキを作っています。
// ケーキは A × B × C センチの直方体です。
//
// このケーキを切り分けて、全て同じサイズの立方体にしたい。
// 切る回数を最小にしてください。
//
// 例: 2 × 6 × 4 のケーキ
//
//   +-----------+
//  /           /|  高さ 4
// +-----------+ |
// |           | |
// |           | +  奥行き 6
// |           |/
// +-----------+
//   幅 2
//
// 最大の立方体サイズは gcd(2, 6, 4) = 2 センチ
// → 2×2×2 の立方体に切り分ける
//
// 切る回数:
// - 幅方向: 2/2 - 1 = 0 回
// - 奥行き方向: 6/2 - 1 = 2 回
// - 高さ方向: 4/2 - 1 = 1 回
// - 合計: 3 回
//
// ============================================================================
// 【解法：GCD（最大公約数）】
// ============================================================================
//
// 【なぜ GCD？】
//
// 立方体のサイズは、A, B, C 全ての約数でなければならない。
// 最大の立方体サイズ = gcd(A, B, C)
//
// 【カット数の計算】
//
// 各辺を g で割った数 - 1 がカット数。
// 例: 6 を 2 で割ると 3 個 → 2 回切る
//
// ============================================================================
// 【計算量】
// ============================================================================
//
// - GCD計算: O(log(max(A, B, C)))
// - 合計: O(log(max(A, B, C)))
//
// ============================================================================

use proconio::input;

fn main() {
    input! {
        a: i64,
        b: i64,
        c: i64,
    }
    println!("{}", solve(a, b, c));
}

/// ユークリッドの互除法で GCD を計算
fn gcd(a: i64, b: i64) -> i64 {
    if b == 0 {
        a
    } else {
        gcd(b, a % b)
    }
}

fn solve(a: i64, b: i64, c: i64) -> i64 {
    // -------------------------------------------------------------------------
    // 【3つの数の GCD】
    //
    // gcd(a, b, c) = gcd(gcd(a, b), c)
    // -------------------------------------------------------------------------
    let g = gcd(gcd(a, b), c);

    // -------------------------------------------------------------------------
    // 【各辺のカット数】
    //
    // n 個に分けるには n-1 回切る
    // -------------------------------------------------------------------------
    let cuts_a = a / g - 1;
    let cuts_b = b / g - 1;
    let cuts_c = c / g - 1;

    cuts_a + cuts_b + cuts_c
}

// =============================================================================
// 【テスト】
// =============================================================================
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn example1() {
        // 2×2×2 → gcd=2, 既に立方体
        // カット数 = 0+0+0 = 0
        assert_eq!(solve(2, 2, 2), 0);
    }

    #[test]
    fn example2() {
        // 2×6×4 → gcd=2
        // カット数 = (1-1)+(3-1)+(2-1) = 0+2+1 = 3
        assert_eq!(solve(2, 6, 4), 3);
    }

    #[test]
    fn example3() {
        // 1×1×1 → gcd=1, 既に立方体
        // カット数 = 0
        assert_eq!(solve(1, 1, 1), 0);
    }

    #[test]
    fn large_gcd() {
        // 12×18×24 → gcd=6
        // カット数 = (2-1)+(3-1)+(4-1) = 1+2+3 = 6
        assert_eq!(solve(12, 18, 24), 6);
    }

    #[test]
    fn gcd_is_one() {
        // 2×3×5 → gcd=1
        // カット数 = (2-1)+(3-1)+(5-1) = 1+2+4 = 7
        assert_eq!(solve(2, 3, 5), 7);
    }

    #[test]
    fn all_same() {
        // 6×6×6 → gcd=6, 既に立方体
        // カット数 = 0
        assert_eq!(solve(6, 6, 6), 0);
    }
}
