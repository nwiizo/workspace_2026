// 048 - I will not drop out (★3)
// https://atcoder.jp/contests/typical90/tasks/typical90_av
//
// ============================================================
// 問題の理解
// ============================================================
//
// 各問題について:
// - 1分かけると B_i 点（部分点）
// - さらに1分かけると A_i 点（満点）になる
//
// K分以内で得られる最大点数を求める
//
// ============================================================
// 解法のポイント
// ============================================================
//
// 各問題の得点を2つに分解:
// - 1分目: B_i 点を獲得
// - 2分目: (A_i - B_i) 点を追加で獲得
//
// 制約 A_i/2 < B_i より、B_i > A_i - B_i
// つまり「1分目の得点 > 2分目の得点」が常に成り立つ！
//
// この性質のおかげで、貪欲に選んでOK:
// - 2分目を選ぶなら、その問題の1分目は既に選ばれているはず
//   （1分目の方が価値が高いので）
//
// したがって:
// 1. すべての「1分あたりの得点」をリストアップ
// 2. 降順ソートして上位K個を選ぶ
//
// ============================================================
// 計算量: O(N log N)
// ============================================================

use proconio::input;

fn main() {
    input! {
        n: usize,
        k: usize,
        problems: [(i64, i64); n], // (A_i, B_i)
    }
    println!("{}", solve(n, k, &problems));
}

fn solve(n: usize, k: usize, problems: &[(i64, i64)]) -> i64 {
    // 各問題を「1分目の得点」と「2分目の得点」に分解
    let mut gains: Vec<i64> = Vec::with_capacity(2 * n);

    for &(a, b) in problems {
        gains.push(b); // 1分目: 部分点
        gains.push(a - b); // 2分目: 満点との差分
    }

    // 降順ソート（大きい順）
    gains.sort_by(|x, y| y.cmp(x));

    // 上位K個の和
    gains.iter().take(k).sum()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_example1() {
        // 問題3の満点(15) + 問題4の部分点(6) = 21
        let problems = vec![(4, 3), (9, 5), (15, 8), (8, 6)];
        assert_eq!(solve(4, 3, &problems), 21);
    }

    #[test]
    fn test_all_partial() {
        // gains = [6, 4, 11, 9] → ソート後 [11, 9, 6, 4]
        // K=2: 11 + 9 = 20 (問題2の満点)
        let problems = vec![(10, 6), (20, 11)];
        assert_eq!(solve(2, 2, &problems), 20);
    }
}
